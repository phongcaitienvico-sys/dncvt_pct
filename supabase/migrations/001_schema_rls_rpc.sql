CREATE OR REPLACE FUNCTION private.distinct_trimmed(p_vals text[])
RETURNS text[]
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v text;
  v_s text;
  v_out text[] := ARRAY[]::text[];
BEGIN
  IF p_vals IS NULL THEN
    RETURN v_out;
  END IF;
  FOREACH v IN ARRAY p_vals LOOP
    v_s := regexp_replace(COALESCE(v, ''), '^[\s\u00A0]+|[\s\u00A0]+$', '', 'g');
    IF NOT (v_s = ANY(v_out)) THEN
      v_out := array_append(v_out, v_s);
    END IF;
  END LOOP;
  RETURN v_out;
END;
$$;

CREATE OR REPLACE FUNCTION private.distinct_nonempty_join(p_vals text[])
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v_dist text[];
  v text;
  v_nonempty text[] := ARRAY[]::text[];
BEGIN
  v_dist := private.distinct_trimmed(p_vals);
  FOREACH v IN ARRAY v_dist LOOP
    IF v <> '' THEN
      v_nonempty := array_append(v_nonempty, v);
    END IF;
  END LOOP;
  RETURN array_to_string(v_nonempty, '; ');
END;
$$;

CREATE OR REPLACE FUNCTION private.check_mixed_jsonb(p_lines jsonb, p_confirmed boolean)
RETURNS void
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v_item jsonb;
  v_proj_in text[] := ARRAY[]::text[];
  v_loc_in text[] := ARRAY[]::text[];
  v_projects text[];
  v_locations text[];
  v_parts text[] := ARRAY[]::text[];
  v_cnt int;
BEGIN
  v_cnt := jsonb_array_length(COALESCE(p_lines, '[]'::jsonb));
  FOR v_item IN SELECT value FROM jsonb_array_elements(COALESCE(p_lines, '[]'::jsonb)) LOOP
    v_proj_in := array_append(v_proj_in, COALESCE(NULLIF(v_item->>'project_code', ''), v_item->>'project_name', ''));
    v_loc_in := array_append(v_loc_in, COALESCE(v_item->>'delivery_location', ''));
  END LOOP;

  v_projects := private.distinct_trimmed(v_proj_in);
  v_locations := private.distinct_trimmed(v_loc_in);

  IF NOT COALESCE(p_confirmed, false) AND (cardinality(v_projects) > 1 OR cardinality(v_locations) > 1) THEN
    IF cardinality(v_projects) > 1 THEN
      v_parts := array_append(v_parts, cardinality(v_projects) || ' hạng mục');
    END IF;
    IF cardinality(v_locations) > 1 THEN
      v_parts := array_append(v_parts, cardinality(v_locations) || ' nơi giao');
    END IF;
    PERFORM private.app_fail(
      v_cnt || ' dòng thuộc ' || array_to_string(v_parts, ' và ') || ', vẫn gộp vào 1 phiếu?',
      'MIXED',
      jsonb_build_object(
        'lines', v_cnt,
        'projects', cardinality(v_projects),
        'locations', cardinality(v_locations)
      )
    );
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION private.build_header_jsonb(p_lines jsonb, p_extra jsonb)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  v_item jsonb;
  v_units text[] := ARRAY[]::text[];
  v_pcodes text[] := ARRAY[]::text[];
  v_pnames text[] := ARRAY[]::text[];
  v_locs text[] := ARRAY[]::text[];
  v_reqs text[] := ARRAY[]::text[];
  v_min_need text := NULL;
  v_nd text;
  v_note text;
BEGIN
  FOR v_item IN SELECT value FROM jsonb_array_elements(COALESCE(p_lines, '[]'::jsonb)) LOOP
    v_units := array_append(v_units, v_item->>'unit');
    v_pcodes := array_append(v_pcodes, v_item->>'project_code');
    v_pnames := array_append(v_pnames, v_item->>'project_name');
    v_locs := array_append(v_locs, v_item->>'delivery_location');
    v_reqs := array_append(v_reqs, v_item->>'requester');
    v_nd := NULLIF(v_item->>'need_date', '');
    IF v_nd IS NOT NULL AND (v_min_need IS NULL OR v_nd < v_min_need) THEN
      v_min_need := v_nd;
    END IF;
  END LOOP;

  v_note := COALESCE(
    CASE
      WHEN p_extra IS NOT NULL AND jsonb_typeof(p_extra) = 'object'
      THEN private.clean_str(p_extra->'note', 'Ghi chú')
      ELSE NULL
    END,
    ''
  );

  RETURN jsonb_build_object(
    'unit', private.distinct_nonempty_join(v_units),
    'project_code', private.distinct_nonempty_join(v_pcodes),
    'project_name', private.distinct_nonempty_join(v_pnames),
    'delivery_location', private.distinct_nonempty_join(v_locs),
    'requester', private.distinct_nonempty_join(v_reqs),
    'request_date', private.today_str(),
    'need_date', v_min_need,
    'note', v_note
  );
END;
$$;

