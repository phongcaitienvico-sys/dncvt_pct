    WHEN 'payers' THEN
      SELECT COALESCE(jsonb_agg(jsonb_build_object(
        'id', id, 'name', name, 'position', position, 'unit', unit
      ) ORDER BY id ASC), '[]'::jsonb) INTO v_out FROM public.payers;
    ELSE
      PERFORM private.app_fail('Danh mục không hợp lệ: ' || COALESCE(p_table, ''));
  END CASE;
  RETURN v_out;
END;
$$;

