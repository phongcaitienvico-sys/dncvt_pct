-- payreq.issue
CREATE OR REPLACE FUNCTION public.rpc_payreq_issue(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_line_ids bigint[];
  v_hdr_in jsonb;
  v_requester text;
  v_header jsonb;
  v_year int;
  v_seq bigint;
  v_code text;
  v_now timestamptz;
  v_total numeric;
BEGIN
  v_me := private.require_user(false);
  v_line_ids := private.lock_payable_lines(p_params->'line_ids');

  v_hdr_in := CASE
    WHEN p_params ? 'header' AND jsonb_typeof(p_params->'header') = 'object' THEN p_params->'header'
    ELSE '{}'::jsonb
  END;
  v_requester := private.clean_str(v_hdr_in->'requester', 'Người đề nghị');
  IF v_requester IS NULL THEN
    PERFORM private.app_fail('Chưa chọn người đề nghị.', 'INVALID');
  END IF;
  v_header := jsonb_build_object(
    'requester', v_requester,
    'position', COALESCE(private.clean_str(v_hdr_in->'position', 'Chức vụ'), ''),
    'unit', COALESCE(private.clean_str(v_hdr_in->'unit', 'Đơn vị'), '')
  );

  v_now := private.app_now();
  v_year := extract(year FROM (v_now AT TIME ZONE 'Asia/Ho_Chi_Minh'))::int;

  INSERT INTO public.sequences (key, last_value)
  VALUES ('DN' || v_year, CASE WHEN v_year = 2026 THEN 15 ELSE 0 END)
  ON CONFLICT (key) DO NOTHING;

  UPDATE public.sequences
  SET last_value = last_value + 1
  WHERE key = 'DN' || v_year
  RETURNING last_value INTO v_seq;

  WHILE EXISTS (
    SELECT 1 FROM public.payment_requests r
    WHERE upper(r.code) = upper(private.format_payreq_code(v_year, v_seq))
  ) LOOP
    UPDATE public.sequences
    SET last_value = last_value + 1
    WHERE key = 'DN' || v_year
    RETURNING last_value INTO v_seq;
  END LOOP;

  v_code := private.format_payreq_code(v_year, v_seq);

  SELECT COALESCE(trim_scale(SUM(COALESCE(l.amount, 0))), 0) INTO v_total
  FROM public.payment_lines l
  WHERE l.id = ANY(v_line_ids);

  INSERT INTO public.payment_requests (
    code, year, seq, issued_at, issued_by, header_json, line_count, total, paid, paid_date, paid_by, legacy_flag
  )
  VALUES (
    v_code,
    v_year,
    v_seq::int,
    v_now,
    COALESCE(NULLIF(v_me.full_name, ''), v_me.username),
    v_header,
    cardinality(v_line_ids),
    v_total,
    false,
    NULL,
    NULL,
    false
  );

  UPDATE public.payment_lines
  SET request_code = v_code,
      updated_at = v_now
  WHERE id = ANY(v_line_ids);

  PERFORM private.write_audit(
    v_me.username,
    'payment_requests',
    v_code,
    '(xuất giấy đề nghị)',
    '',
    array_to_string(v_line_ids::text[], ',')
  );

  RETURN jsonb_build_object(
    'code', v_code,
    'line_ids', to_jsonb(v_line_ids)
  );
END;
$$;

-- payreq.append
CREATE OR REPLACE FUNCTION public.rpc_payreq_append(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_line_ids bigint[];
  v_code_in text;
  v_req public.payment_requests;
  v_cur_cnt int;
BEGIN
  v_me := private.require_user(false);
  v_line_ids := private.lock_payable_lines(p_params->'line_ids');

  v_code_in := upper(btrim(COALESCE(p_params->>'code', '')));
  IF v_code_in = '' THEN
    PERFORM private.app_fail('Chưa nhập số giấy đề nghị.');
  END IF;

  SELECT * INTO v_req
  FROM public.payment_requests r
  WHERE upper(r.code) = v_code_in
  FOR UPDATE;
  IF NOT FOUND THEN
    PERFORM private.app_fail('Không tìm thấy giấy đề nghị ' || v_code_in || '.', 'NOT_FOUND');
  END IF;
  IF v_req.paid AND v_me.role <> 'admin' THEN
    PERFORM private.app_fail(
      'Giấy ' || v_req.code || ' đã thanh toán: chỉ Quản trị được thêm dòng.',
      'PAID'
    );
  END IF;

  SELECT count(*)::int INTO v_cur_cnt FROM public.payment_lines WHERE request_code = v_req.code;
  IF v_cur_cnt + cardinality(v_line_ids) > 200 THEN
    PERFORM private.app_fail(
      'Giấy ' || v_req.code || ' đã có ' || v_cur_cnt || ' dòng, thêm ' || cardinality(v_line_ids) || ' dòng sẽ vượt quá 200 dòng/giấy.'
    );
  END IF;

  UPDATE public.payment_lines
  SET request_code = v_req.code,
      updated_at = private.app_now()
  WHERE id = ANY(v_line_ids);

  PERFORM private.payreq_recalc(v_req.code);

  PERFORM private.write_audit(
    v_me.username,
    'payment_requests',
    v_req.code,
    '(thêm dòng vào giấy đề nghị)',
    '',
    array_to_string(v_line_ids::text[], ',')
  );

  RETURN jsonb_build_object(
    'code', v_req.code,
    'line_ids', to_jsonb(v_line_ids)
  );
END;
$$;

-- payreq.detach (Admin)
CREATE OR REPLACE FUNCTION public.rpc_payreq_detach(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_ids bigint[];
  v_line public.payment_lines;
  v_detach_ids bigint[] := ARRAY[]::bigint[];
  v_codes text[] := ARRAY[]::text[];
  v_code text;
  v_now timestamptz;
BEGIN
  v_me := private.require_user(true);
  v_ids := private.clean_ids(p_params->'line_ids');
  IF cardinality(v_ids) = 0 THEN
    PERFORM private.app_fail('Chưa chọn dòng nào.');
  END IF;

  v_now := private.app_now();
  FOR v_line IN SELECT * FROM public.payment_lines WHERE id = ANY(v_ids) ORDER BY id FOR UPDATE LOOP
    IF v_line.request_code IS NOT NULL AND v_line.request_code <> '' THEN
      v_detach_ids := array_append(v_detach_ids, v_line.id);
      IF NOT (v_line.request_code = ANY(v_codes)) THEN
        v_codes := array_append(v_codes, v_line.request_code);
      END IF;
    END IF;
  END LOOP;

  IF cardinality(v_detach_ids) = 0 THEN
    PERFORM private.app_fail('Các dòng đã chọn chưa thuộc giấy đề nghị nào.');
  END IF;

  PERFORM 1 FROM public.payment_requests WHERE code = ANY(v_codes) ORDER BY id FOR UPDATE;

  FOR v_line IN SELECT * FROM public.payment_lines WHERE id = ANY(v_detach_ids) ORDER BY id LOOP
    UPDATE public.payment_lines
    SET request_code = NULL,
        updated_at = v_now
    WHERE id = v_line.id;

    PERFORM private.write_audit(
      v_me.username,
      'payment_lines',
      v_line.id::text,
      'request_code',
      v_line.request_code,
      '(gỡ khỏi giấy đề nghị)'
    );
  END LOOP;

  FOREACH v_code IN ARRAY v_codes LOOP
    PERFORM private.payreq_recalc(v_code);
  END LOOP;

  RETURN jsonb_build_object('detached', cardinality(v_detach_ids));
END;
$$;

