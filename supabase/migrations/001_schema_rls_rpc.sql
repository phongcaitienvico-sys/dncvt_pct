CREATE OR REPLACE FUNCTION public.rpc_audit_list(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_limit int;
  v_q text;
  v_pattern text;
  v_out jsonb;
BEGIN
  PERFORM private.require_user(true);
  v_limit := LEAST(GREATEST(COALESCE(NULLIF(p_params->>'limit', '')::int, 500), 1), 5000);
  v_q := lower(COALESCE(p_params->>'q', ''));
  v_pattern := '%' || replace(replace(replace(v_q, '\', '\\'), '%', '\%'), '_', '\_') || '%';

  SELECT COALESCE(jsonb_agg(private.audit_to_jsonb(sub)), '[]'::jsonb)
    INTO v_out
  FROM (
    SELECT a.*
    FROM public.audit_log a
    WHERE v_q = ''
       OR lower(concat_ws(' ', a."user", a."table", a.row_id, a.field, a."old", a."new")) LIKE v_pattern ESCAPE '\'
    ORDER BY a.id DESC
    LIMIT v_limit
  ) sub;

  RETURN v_out;
END;
$$;

