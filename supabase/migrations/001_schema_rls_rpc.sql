-- 7.11 Requests Detach (Admin)
CREATE OR REPLACE FUNCTION public.rpc_requests_detach(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_ids bigint[];
  v_id bigint;
  v_line public.lines;
  v_detach_ids bigint[] := ARRAY[]::bigint[];
  v_codes text[] := ARRAY[]::text[];
  v_code text;
  v_cnt int;
  v_now timestamptz;
BEGIN
  v_me := private.require_user(true);
  v_ids := private.clean_ids(p_params->'line_ids');
  IF cardinality(v_ids) = 0 THEN
    PERFORM private.app_fail('Chưa chọn dòng nào.');
  END IF;

  PERFORM 1 FROM public.lines WHERE id = ANY(v_ids) ORDER BY id FOR UPDATE;

  FOREACH v_id IN ARRAY v_ids LOOP
    SELECT * INTO v_line FROM public.lines WHERE id = v_id;
    IF FOUND AND v_line.request_code IS NOT NULL AND v_line.request_code <> '' THEN
      v_detach_ids := array_append(v_detach_ids, v_id);
      IF NOT (v_line.request_code = ANY(v_codes)) THEN
        v_codes := array_append(v_codes, v_line.request_code);
      END IF;
    END IF;
  END LOOP;

  IF cardinality(v_detach_ids) = 0 THEN
    PERFORM private.app_fail('Các dòng đã chọn chưa thuộc phiếu nào.');
  END IF;

  FOREACH v_code IN ARRAY v_codes LOOP
    SELECT count(*)::int INTO v_cnt
    FROM public.lines l
    WHERE l.id = ANY(v_detach_ids) AND l.request_code = v_code;

    UPDATE public.requests
    SET line_count = GREATEST(0, COALESCE(line_count, 0) - v_cnt)
    WHERE code = v_code;
  END LOOP;

  v_now := private.app_now();
  FOREACH v_id IN ARRAY v_detach_ids LOOP
    SELECT * INTO v_line FROM public.lines WHERE id = v_id;
    UPDATE public.lines
    SET request_code = NULL,
        updated_at = v_now
    WHERE id = v_id;

    PERFORM private.write_audit(
      v_me.username,
      'lines',
      v_id::text,
      'request_code',
      v_line.request_code,
      '(gỡ khỏi phiếu)'
    );
  END LOOP;

  RETURN jsonb_build_object(
    'line_ids', to_jsonb(v_detach_ids),
    'requests', to_jsonb(v_codes)
  );
END;
$$;

-- 7.12 Requests Get & Requests List
CREATE OR REPLACE FUNCTION public.rpc_requests_get(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_raw jsonb;
  v_elem jsonb;
  v_c text;
  v_codes text[] := ARRAY[]::text[];
  v_not_found text[] := ARRAY[]::text[];
  v_req public.requests;
  v_lines jsonb;
  v_out jsonb := '[]'::jsonb;
BEGIN
  PERFORM private.require_user(false);
  v_raw := p_params->'codes';
  IF v_raw IS NULL OR jsonb_typeof(v_raw) <> 'array' OR jsonb_array_length(v_raw) = 0 THEN
    PERFORM private.app_fail('Chưa có số phiếu.');
  END IF;
  IF jsonb_array_length(v_raw) > 100 THEN
    PERFORM private.app_fail('Tối đa 100 phiếu mỗi lần in.');
  END IF;

  FOR v_elem IN SELECT value FROM jsonb_array_elements(v_raw) LOOP
    v_c := upper(btrim(COALESCE(v_elem #>> '{}', '')));
    IF v_c <> '' AND NOT (v_c = ANY(v_codes)) THEN
      v_codes := array_append(v_codes, v_c);
    END IF;
  END LOOP;

  FOREACH v_c IN ARRAY v_codes LOOP
    IF NOT EXISTS (SELECT 1 FROM public.requests r WHERE upper(r.code) = v_c) THEN
      v_not_found := array_append(v_not_found, v_c);
    END IF;
  END LOOP;
  IF cardinality(v_not_found) > 0 THEN
    PERFORM private.app_fail('Không tìm thấy phiếu: ' || array_to_string(v_not_found, ', '), 'NOT_FOUND');
  END IF;

  FOREACH v_c IN ARRAY v_codes LOOP
    SELECT * INTO v_req FROM public.requests r WHERE upper(r.code) = v_c LIMIT 1;
    SELECT COALESCE(jsonb_agg(private.line_to_jsonb(l) ORDER BY l.id ASC), '[]'::jsonb)
      INTO v_lines
    FROM public.lines l
    WHERE upper(COALESCE(l.request_code, '')) = v_c;

    v_out := v_out || jsonb_build_array(jsonb_build_object(
      'request', private.request_to_jsonb(v_req),
      'lines', v_lines
    ));
  END LOOP;

  RETURN v_out;
END;
$$;

CREATE OR REPLACE FUNCTION public.rpc_requests_list(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_out jsonb;
BEGIN
  PERFORM private.require_user(false);
  WITH agg AS (
    SELECT
      l.request_code AS code,
      count(*)::int AS cnt,
      COALESCE(SUM(COALESCE(l.qty_requested, 0) * COALESCE(l.unit_price, 0)), 0) AS amount,
      private.distinct_nonempty_join(array_agg(l.supplier ORDER BY l.id ASC)) AS suppliers
    FROM public.lines l
    WHERE l.request_code IS NOT NULL AND l.request_code <> ''
    GROUP BY l.request_code
  )
  SELECT COALESCE(jsonb_agg(
    private.request_to_jsonb(r) || jsonb_build_object(
      'line_count', COALESCE(a.cnt, 0),
      'amount', private.num_json(COALESCE(a.amount, 0)),
      'suppliers', COALESCE(a.suppliers, '')
    )
    ORDER BY COALESCE(private.fmt_ts(r.issued_at), '') DESC, r.id DESC
  ), '[]'::jsonb)
  INTO v_out
  FROM public.requests r
  LEFT JOIN agg a ON a.code = r.code;

  RETURN v_out;
END;
$$;

