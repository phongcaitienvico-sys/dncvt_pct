-- payreq.get
CREATE OR REPLACE FUNCTION public.rpc_payreq_get(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_raw jsonb;
  v_elem jsonb;
  v_c text;
  v_codes text[] := ARRAY[]::text[];
  v_not_found text[] := ARRAY[]::text[];
  v_req public.payment_requests;
  v_lines jsonb;
  v_out jsonb := '[]'::jsonb;
BEGIN
  PERFORM private.require_user(false);
  v_raw := p_params->'codes';
  IF v_raw IS NULL OR jsonb_typeof(v_raw) <> 'array' OR jsonb_array_length(v_raw) = 0 THEN
    PERFORM private.app_fail('Chưa có số giấy đề nghị.');
  END IF;
  IF jsonb_array_length(v_raw) > 100 THEN
    PERFORM private.app_fail('Tối đa 100 giấy mỗi lần in.');
  END IF;

  FOR v_elem IN SELECT value FROM jsonb_array_elements(v_raw) LOOP
    v_c := upper(btrim(COALESCE(v_elem #>> '{}', '')));
    IF v_c <> '' AND NOT (v_c = ANY(v_codes)) THEN
      v_codes := array_append(v_codes, v_c);
    END IF;
  END LOOP;

  FOREACH v_c IN ARRAY v_codes LOOP
    IF NOT EXISTS (SELECT 1 FROM public.payment_requests r WHERE upper(r.code) = v_c) THEN
      v_not_found := array_append(v_not_found, v_c);
    END IF;
  END LOOP;
  IF cardinality(v_not_found) > 0 THEN
    PERFORM private.app_fail('Không tìm thấy giấy đề nghị: ' || array_to_string(v_not_found, ', '), 'NOT_FOUND');
  END IF;

  FOREACH v_c IN ARRAY v_codes LOOP
    SELECT * INTO v_req FROM public.payment_requests r WHERE upper(r.code) = v_c LIMIT 1;
    SELECT COALESCE(jsonb_agg(private.payment_line_to_jsonb(l) ORDER BY l.pay_date ASC NULLS LAST, l.id ASC), '[]'::jsonb)
      INTO v_lines
    FROM public.payment_lines l
    WHERE l.request_code = v_req.code;

    v_out := v_out || jsonb_build_array(jsonb_build_object(
      'code', v_req.code,
      'issued_at', private.fmt_ts(v_req.issued_at),
      'issued_by', v_req.issued_by,
      'header', jsonb_build_object(
        'requester', COALESCE(v_req.header_json->>'requester', ''),
        'position', COALESCE(v_req.header_json->>'position', ''),
        'unit', COALESCE(v_req.header_json->>'unit', '')
      ),
      'line_count', COALESCE(v_req.line_count, 0),
      'total', private.num_json(COALESCE(v_req.total, 0)),
      'paid', COALESCE(v_req.paid, false),
      'paid_date', private.fmt_date(v_req.paid_date),
      'paid_by', v_req.paid_by,
      'legacy_flag', COALESCE(v_req.legacy_flag, false),
      'lines', v_lines
    ));
  END LOOP;

  RETURN v_out;
END;
$$;

-- payreq.setPaid
CREATE OR REPLACE FUNCTION public.rpc_payreq_set_paid(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_code_in text;
  v_req public.payment_requests;
  v_after public.payment_requests;
  v_paid boolean;
  v_date date;
  v_old text;
  v_new text;
BEGIN
  v_me := private.require_user(false);
  v_code_in := upper(btrim(COALESCE(p_params->>'code', '')));
  IF v_code_in = '' THEN
    PERFORM private.app_fail('Chưa có số giấy đề nghị.');
  END IF;
  IF p_params->'paid' IS NULL OR jsonb_typeof(p_params->'paid') <> 'boolean' THEN
    PERFORM private.app_fail('Trạng thái thanh toán không hợp lệ.');
  END IF;
  v_paid := (p_params->>'paid')::boolean;

  SELECT * INTO v_req
  FROM public.payment_requests r
  WHERE upper(r.code) = v_code_in
  FOR UPDATE;
  IF NOT FOUND THEN
    PERFORM private.app_fail('Không tìm thấy giấy đề nghị ' || v_code_in || '.', 'NOT_FOUND');
  END IF;

  IF v_paid THEN
    v_date := COALESCE(private.clean_date(p_params->'paid_date', 'Ngày thanh toán'), private.today_date());
    UPDATE public.payment_requests
    SET paid = true,
        paid_date = v_date,
        paid_by = COALESCE(NULLIF(v_me.full_name, ''), v_me.username)
    WHERE id = v_req.id
    RETURNING * INTO v_after;
  ELSE
    UPDATE public.payment_requests
    SET paid = false,
        paid_date = NULL,
        paid_by = NULL
    WHERE id = v_req.id
    RETURNING * INTO v_after;
  END IF;

  v_old := CASE WHEN v_req.paid THEN 'Đã TT ' || COALESCE(private.fmt_date(v_req.paid_date), '') ELSE 'Chưa TT' END;
  v_new := CASE WHEN v_after.paid THEN 'Đã TT ' || COALESCE(private.fmt_date(v_after.paid_date), '') ELSE 'Chưa TT' END;
  PERFORM private.write_audit(v_me.username, 'payment_requests', v_after.code, 'paid', v_old, v_new);

  RETURN private.payreq_row_jsonb(v_after);
END;
$$;

