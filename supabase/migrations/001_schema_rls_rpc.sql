CREATE OR REPLACE FUNCTION public.rpc_admin_check_login(p_username text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_clean text;
  v_key text;
  v_att private.login_attempts;
  v_prof public.profiles;
  v_email text;
BEGIN
  v_clean := COALESCE(private.clean_str(to_jsonb(p_username), 'Tên đăng nhập'), '');
  v_key := lower(v_clean);

  SELECT * INTO v_att FROM private.login_attempts WHERE username = v_key;
  IF FOUND AND v_att.window_until > private.app_now() AND v_att.fail_count >= 5 THEN
    PERFORM private.app_fail('Sai mật khẩu quá 5 lần. Thử lại sau 15 phút.', 'LOCKED');
  END IF;

  IF v_clean = '' THEN
    RETURN jsonb_build_object('found', false, 'active', false, 'auth_id', NULL, 'email', NULL, 'user', NULL);
  END IF;

  SELECT p.id, p.username, p.full_name, p.role, p.active, p.created_at, u.email
    INTO v_prof.id, v_prof.username, v_prof.full_name, v_prof.role, v_prof.active, v_prof.created_at, v_email
  FROM public.profiles p
  LEFT JOIN auth.users u ON u.id = p.id
  WHERE lower(p.username) = v_key;

  IF NOT FOUND THEN
    RETURN jsonb_build_object('found', false, 'active', false, 'auth_id', NULL, 'email', NULL, 'user', NULL);
  END IF;

  RETURN jsonb_build_object(
    'found', true,
    'active', v_prof.active,
    'auth_id', v_prof.id,
    'email', v_email,
    'user', private.profile_to_jsonb(v_prof)
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.rpc_admin_record_login(p_username text, p_ok boolean)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_key text;
  v_cnt int := 0;
BEGIN
  v_key := lower(btrim(COALESCE(p_username, '')));
  IF p_ok THEN
    DELETE FROM private.login_attempts WHERE username = v_key;
    RETURN jsonb_build_object('ok', true, 'fail_count', 0);
  END IF;

  INSERT INTO private.login_attempts (username, fail_count, window_until)
  VALUES (v_key, 1, private.app_now() + interval '15 minutes')
  ON CONFLICT (username) DO UPDATE
    SET fail_count = CASE
          WHEN private.login_attempts.window_until > private.app_now()
          THEN private.login_attempts.fail_count + 1
          ELSE 1
        END,
        window_until = private.app_now() + interval '15 minutes'
  RETURNING fail_count INTO v_cnt;

  RETURN jsonb_build_object('ok', false, 'fail_count', v_cnt);
END;
$$;

CREATE OR REPLACE FUNCTION public.rpc_admin_save_profile_and_sessions(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_mode text;
  v_actor_auth_id uuid;
  v_keep_session_id uuid;
  v_actor public.profiles;
  v_target public.profiles;
  v_dup public.profiles;
  v_email text;
  v_id uuid;
  v_auth_id uuid;
  v_username text;
  v_full_name text;
  v_role text;
  v_active boolean;
  v_pw_changed boolean;
  v_validate_only boolean;
  v_after public.profiles;
BEGIN
  v_mode := COALESCE(p_params->>'mode', 'save_user');

  IF v_mode = 'actor_info' THEN
    v_actor_auth_id := NULLIF(p_params->>'actor_auth_id', '')::uuid;
    IF v_actor_auth_id IS NULL THEN
      PERFORM private.app_fail('Phiên đăng nhập hết hạn, vui lòng đăng nhập lại.', 'AUTH');
    END IF;
    SELECT p.id, p.username, p.full_name, p.role, p.active, p.created_at, u.email
      INTO v_actor.id, v_actor.username, v_actor.full_name, v_actor.role, v_actor.active, v_actor.created_at, v_email
    FROM public.profiles p
    LEFT JOIN auth.users u ON u.id = p.id
    WHERE p.id = v_actor_auth_id AND p.active = true;
    IF NOT FOUND THEN
      PERFORM private.app_fail('Phiên đăng nhập hết hạn, vui lòng đăng nhập lại.', 'AUTH');
    END IF;
    RETURN jsonb_build_object(
      'profile', private.profile_to_jsonb(v_actor),
      'auth_id', v_actor.id,
      'email', v_email
    );
  END IF;

  IF v_mode = 'change_password' THEN
    v_actor_auth_id := NULLIF(p_params->>'actor_auth_id', '')::uuid;
    BEGIN
      v_keep_session_id := NULLIF(p_params->>'keep_session_id', '')::uuid;
    EXCEPTION WHEN OTHERS THEN
      v_keep_session_id := NULL;
    END;
    SELECT * INTO v_actor FROM public.profiles WHERE id = v_actor_auth_id AND active = true FOR UPDATE;
    IF NOT FOUND THEN
      PERFORM private.app_fail('Phiên đăng nhập hết hạn, vui lòng đăng nhập lại.', 'AUTH');
    END IF;
    PERFORM private.write_audit(v_actor.username, 'users', v_actor.id::text, 'password', '', '(đã đổi)');
    DELETE FROM auth.sessions
    WHERE user_id = v_actor.id
      AND (v_keep_session_id IS NULL OR id <> v_keep_session_id);
    RETURN private.profile_to_jsonb(v_actor);
  END IF;

  -- Chế độ mặc định: Admin lưu người dùng (kiểm tra trước hoặc upsert thật)
  v_actor_auth_id := NULLIF(p_params->>'actor_auth_id', '')::uuid;
  IF v_actor_auth_id IS NULL THEN
    PERFORM private.app_fail('Phiên đăng nhập hết hạn, vui lòng đăng nhập lại.', 'AUTH');
  END IF;
  SELECT * INTO v_actor FROM public.profiles WHERE id = v_actor_auth_id AND active = true;
  IF NOT FOUND THEN
    PERFORM private.app_fail('Phiên đăng nhập hết hạn, vui lòng đăng nhập lại.', 'AUTH');
  END IF;
  IF v_actor.role <> 'admin' THEN
    PERFORM private.app_fail('Chỉ Quản trị được thực hiện thao tác này.', 'FORBIDDEN');
  END IF;

  PERFORM pg_advisory_xact_lock(hashtext('profiles:save'));

  v_username := private.clean_str(p_params->'username', 'Tên đăng nhập');
  IF v_username IS NULL OR v_username !~ '^[a-zA-Z0-9._-]{3,40}$' THEN
    PERFORM private.app_fail('Tên đăng nhập 3–40 ký tự: chữ không dấu, số, . _ -');
  END IF;
  v_role := CASE WHEN (p_params->>'role') = 'admin' THEN 'admin' ELSE 'user' END;
  v_full_name := COALESCE(private.clean_str(p_params->'full_name', 'Họ tên'), v_username);
  v_active := CASE WHEN p_params ? 'active' AND (p_params->>'active') = 'false' THEN false ELSE true END;
  v_pw_changed := COALESCE((p_params->>'password_changed')::boolean, false);
  v_validate_only := COALESCE((p_params->>'validate_only')::boolean, false);

  SELECT * INTO v_dup FROM public.profiles WHERE lower(username) = lower(v_username);

  IF p_params ? 'id' AND p_params->'id' IS NOT NULL AND jsonb_typeof(p_params->'id') <> 'null' AND (p_params->>'id') <> '' THEN
    BEGIN
      v_id := btrim(p_params->>'id')::uuid;
    EXCEPTION WHEN OTHERS THEN
      PERFORM private.app_fail('Id người dùng không hợp lệ: ' || COALESCE(p_params->>'id', ''));
    END;
    SELECT * INTO v_target FROM public.profiles WHERE id = v_id FOR UPDATE;
    IF NOT FOUND THEN
      PERFORM private.app_fail('Không tìm thấy người dùng', 'NOT_FOUND');
    END IF;
    IF v_dup.id IS NOT NULL AND v_dup.id <> v_id THEN
      PERFORM private.app_fail('Tên đăng nhập đã tồn tại');
    END IF;
    IF v_id = v_actor.id AND (v_role <> 'admin' OR NOT v_active) THEN
      PERFORM private.app_fail('Không thể tự bỏ quyền Quản trị hoặc tự khóa tài khoản của mình.');
    END IF;

    IF v_validate_only THEN
      RETURN jsonb_build_object(
        'target_id', v_target.id,
        'target_auth_id', v_target.id,
        'username', v_username,
        'full_name', v_full_name,
        'role', v_role,
        'active', v_active
      );
    END IF;

    UPDATE public.profiles
    SET username = v_username,
        full_name = v_full_name,
        role = v_role,
        active = v_active
    WHERE id = v_id
    RETURNING * INTO v_after;

    IF v_target.username IS DISTINCT FROM v_after.username THEN
      PERFORM private.write_audit(v_actor.username, 'users', v_id::text, 'username', v_target.username, v_after.username);
    END IF;
    IF v_target.full_name IS DISTINCT FROM v_after.full_name THEN
      PERFORM private.write_audit(v_actor.username, 'users', v_id::text, 'full_name', v_target.full_name, v_after.full_name);
    END IF;
    IF v_target.role IS DISTINCT FROM v_after.role THEN
      PERFORM private.write_audit(v_actor.username, 'users', v_id::text, 'role', v_target.role, v_after.role);
    END IF;
    IF v_target.active IS DISTINCT FROM v_after.active THEN
      PERFORM private.write_audit(v_actor.username, 'users', v_id::text, 'active', v_target.active::text, v_after.active::text);
    END IF;
    IF v_pw_changed THEN
      PERFORM private.write_audit(v_actor.username, 'users', v_id::text, 'password', '', '(đặt lại)');
    END IF;

    IF NOT v_active OR v_pw_changed THEN
      DELETE FROM auth.sessions WHERE user_id = v_after.id;
    END IF;

    RETURN private.profile_to_jsonb(v_after);
  ELSE
    IF v_dup.id IS NOT NULL THEN
      PERFORM private.app_fail('Tên đăng nhập đã tồn tại');
    END IF;
    IF v_validate_only THEN
      RETURN jsonb_build_object(
        'target_id', NULL,
        'target_auth_id', NULL,
        'username', v_username,
        'full_name', v_full_name,
        'role', v_role,
        'active', v_active
      );
    END IF;

    v_auth_id := NULLIF(p_params->>'auth_id', '')::uuid;
    IF v_auth_id IS NULL THEN
      PERFORM private.app_fail('Thiếu định danh xác thực (auth_id).');
    END IF;
    INSERT INTO public.profiles (id, username, full_name, role, active, created_at)
    VALUES (v_auth_id, v_username, v_full_name, v_role, v_active, private.app_now())
    ON CONFLICT (id) DO UPDATE
      SET username = EXCLUDED.username,
          full_name = EXCLUDED.full_name,
          role = EXCLUDED.role,
          active = EXCLUDED.active
    RETURNING * INTO v_after;

    PERFORM private.write_audit(v_actor.username, 'users', v_after.id::text, '(thêm)', '', v_username);

    IF NOT v_active THEN
      DELETE FROM auth.sessions WHERE user_id = v_after.id;
    END IF;

    RETURN private.profile_to_jsonb(v_after);
  END IF;
END;
$$;

-- Helper khởi tạo danh mục mẫu & chuẩn hóa Nhóm VT lịch sử (tương đương Setup.js, chỉ service_role)
CREATE OR REPLACE FUNCTION public.rpc_admin_setup(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_grp record;
  v_cur_id bigint := NULL;
  v_parts text[] := ARRAY[]::text[];
  v_remove_ids bigint[] := ARRAY[]::bigint[];
  v_text text;
  v_part text;
  v_lookup jsonb := '{}'::jsonb;
  v_code_by_fold jsonb := '{}'::jsonb;
  v_seg text;
  v_k text;
  v_alias record;
  v_line record;
  v_mapped text;
  v_now timestamptz := private.app_now();
  v_admin_auth_id uuid;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.units) THEN
    INSERT INTO public.units (name) VALUES ('Phòng Kỹ thuật'), ('Xưởng Cơ khí'), ('Phòng Kế hoạch vật tư');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.uoms) THEN
    INSERT INTO public.uoms (name) VALUES
      ('Cái'), ('Bộ'), ('Chiếc'), ('Kg'), ('Mét'), ('Tấm'), ('Cây'), ('Lít'), ('Hộp'), ('Cuộn'), ('Đôi');
  END IF;

  -- Chuẩn hóa material_groups (y hệt migrateMaterialGroups_ trong Setup.js)
  IF NOT EXISTS (SELECT 1 FROM public.material_groups) THEN
    INSERT INTO public.material_groups (name, description) VALUES
      ('C', 'Thiết bị, máy móc sản xuất, vật tư cải tạo, chế tạo; Công cụ, dụng cụ, vật tư phục vụ sửa chữa; Vật tư phục vụ thi công xây dựng'),
      ('E', 'Văn phòng phẩm; Bảo hộ lao động; Đá mài, đá cắt; Các vật tư khác');
  ELSIF (
    NOT EXISTS (SELECT 1 FROM public.material_groups WHERE description IS NOT NULL AND btrim(description) <> '')
    AND EXISTS (SELECT 1 FROM public.material_groups WHERE COALESCE(name, '') ~* '^[A-Z0-9]{1,3}$')
    AND EXISTS (SELECT 1 FROM public.material_groups WHERE char_length(COALESCE(name, '')) > 3)
  ) THEN
    FOR v_grp IN SELECT id, name FROM public.material_groups ORDER BY id ASC LOOP
      v_text := btrim(COALESCE(v_grp.name, ''));
      IF v_text ~* '^[A-Z0-9]{1,3}$' THEN
        IF v_cur_id IS NOT NULL AND cardinality(v_parts) > 0 THEN
          UPDATE public.material_groups SET description = array_to_string(v_parts, '; ') WHERE id = v_cur_id;
        END IF;
        v_cur_id := v_grp.id;
        v_parts := ARRAY[]::text[];
      ELSIF v_cur_id IS NOT NULL THEN
        v_part := btrim(regexp_replace(v_text, '[.;]+$', ''));
        IF v_part <> '' AND NOT (v_part = ANY(v_parts)) THEN
          v_parts := array_append(v_parts, v_part);
        END IF;
        v_remove_ids := array_append(v_remove_ids, v_grp.id);
      END IF;
    END LOOP;
    IF v_cur_id IS NOT NULL AND cardinality(v_parts) > 0 THEN
      UPDATE public.material_groups SET description = array_to_string(v_parts, '; ') WHERE id = v_cur_id;
    END IF;
    IF cardinality(v_remove_ids) > 0 THEN
      DELETE FROM public.material_groups WHERE id = ANY(v_remove_ids);
    END IF;
  END IF;

  FOR v_grp IN SELECT name, description FROM public.material_groups ORDER BY id ASC LOOP
    IF v_grp.name IS NOT NULL AND btrim(v_grp.name) <> '' THEN
      v_k := private.fold_vi(v_grp.name);
      v_code_by_fold := v_code_by_fold || jsonb_build_object(v_k, v_grp.name);
      v_lookup := v_lookup || jsonb_build_object(v_k, v_grp.name);
    END IF;
  END LOOP;

  FOR v_grp IN SELECT name, description FROM public.material_groups ORDER BY id ASC LOOP
    IF v_grp.description IS NOT NULL THEN
      FOREACH v_seg IN ARRAY string_to_array(v_grp.description, ';') LOOP
        v_k := private.fold_vi(v_seg);
        IF v_k <> '' AND NOT (v_lookup ? v_k) THEN
          v_lookup := v_lookup || jsonb_build_object(v_k, v_grp.name);
        END IF;
      END LOOP;
    END IF;
  END LOOP;

  FOR v_alias IN
    SELECT * FROM (VALUES
      ('vt che tao', 'c'), ('bulong', 'c'), ('gcck', 'c'), ('vbi', 'c'),
      ('cat ton', 'c'), ('cong cu ca nhan', 'c'), ('thiet bi', 'c'),
      ('van phong pham', 'e'), ('vt van phong', 'e'), ('do gia dung', 'e')
    ) AS t(alias_key, target_key)
  LOOP
    IF (v_code_by_fold ? v_alias.target_key) AND NOT (v_lookup ? v_alias.alias_key) THEN
      v_lookup := v_lookup || jsonb_build_object(v_alias.alias_key, v_code_by_fold->>v_alias.target_key);
    END IF;
  END LOOP;

  FOR v_line IN SELECT id, material_group FROM public.lines WHERE material_group IS NOT NULL AND btrim(material_group) <> '' LOOP
    v_k := private.fold_vi(v_line.material_group);
    v_mapped := v_lookup->>v_k;
    IF v_mapped IS NOT NULL AND v_mapped <> btrim(v_line.material_group) THEN
      UPDATE public.lines
      SET material_group = v_mapped,
          updated_at = v_now
      WHERE id = v_line.id;
    END IF;
  END LOOP;

  IF NOT EXISTS (SELECT 1 FROM public.signers) THEN
    INSERT INTO public.signers (unit_contains, position, title, name) VALUES
      (NULL, '1', 'Người lập phiếu', NULL),
      (NULL, '2', 'Người xem xét', 'Vũ Văn Trường'),
      (NULL, '3', 'T.P Thiết bị', 'Vũ Văn Trường'),
      (NULL, '4', 'Giám đốc duyệt', 'Phạm Danh Mạnh'),
      ('Cải tiến', '1', 'Người lập phiếu', NULL),
      ('Cải tiến', '2', 'Người xem xét', 'Trần Việt Tiệp'),
      ('Cải tiến', '3', 'T.P Cải tiến', 'Trần Việt Tiệp'),
      ('Cải tiến', '4', 'Giám đốc duyệt', 'Phạm Danh Mạnh');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.suppliers) THEN
    INSERT INTO public.suppliers (code, name, field) VALUES ('KHVT', 'Phòng Kế hoạch vật tư', 'Nội bộ');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.project_items) THEN
    INSERT INTO public.project_items (project_code, project_name, item_code, item_name, status)
    VALUES ('DA01', 'Dự án mẫu', 'HM01', 'Hạng mục mẫu', 'Đang làm');
  END IF;

  INSERT INTO public.sequences (key, last_value)
  VALUES ('YC2026', 294)
  ON CONFLICT (key) DO NOTHING;

  v_admin_auth_id := NULLIF(p_params->>'admin_auth_id', '')::uuid;
  IF v_admin_auth_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.profiles) THEN
    INSERT INTO public.profiles (id, username, full_name, role, active, created_at)
    VALUES (v_admin_auth_id, 'admin', 'Quản trị', 'admin', true, v_now)
    ON CONFLICT (id) DO NOTHING;
  END IF;

  RETURN jsonb_build_object(
    'has_users', EXISTS (SELECT 1 FROM public.profiles)
  );
END;
