DECLARE
  v_tbl text;
BEGIN
  FOREACH v_tbl IN ARRAY ARRAY['payers', 'payment_requests', 'payment_lines'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', v_tbl);
    EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', v_tbl);
    EXECUTE format('DROP POLICY IF EXISTS p_service_all ON public.%I;', v_tbl);
    EXECUTE format(
      'CREATE POLICY p_service_all ON public.%I FOR ALL TO postgres, service_role USING (true) WITH CHECK (true);',
      v_tbl
    );
    EXECUTE format('DROP POLICY IF EXISTS p_auth_select ON public.%I;', v_tbl);
    EXECUTE format(
      'CREATE POLICY p_auth_select ON public.%I FOR SELECT TO authenticated USING (private.is_active_user());',
      v_tbl
    );
  END LOOP;
END
$$;

