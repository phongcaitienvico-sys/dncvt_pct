CREATE OR REPLACE FUNCTION private.catalog_table_jsonb(p_table text)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_out jsonb;
BEGIN
  CASE p_table
    WHEN 'suppliers' THEN
      SELECT COALESCE(jsonb_agg(jsonb_build_object(
        'id', id, 'code', code, 'name', name, 'address', address,
        'phone', phone, 'email', email, 'tax_code', tax_code, 'field', field
      ) ORDER BY id ASC), '[]'::jsonb) INTO v_out FROM public.suppliers;
    WHEN 'project_items' THEN
      SELECT COALESCE(jsonb_agg(jsonb_build_object(
        'id', id, 'project_code', project_code, 'project_name', project_name,
        'item_code', item_code, 'item_name', item_name, 'owner', owner, 'status', status
      ) ORDER BY id ASC), '[]'::jsonb) INTO v_out FROM public.project_items;
    WHEN 'material_groups' THEN
      SELECT COALESCE(jsonb_agg(jsonb_build_object(
        'id', id, 'name', name, 'description', description
      ) ORDER BY id ASC), '[]'::jsonb) INTO v_out FROM public.material_groups;
    WHEN 'signers' THEN
      SELECT COALESCE(jsonb_agg(jsonb_build_object(
        'id', id, 'unit_contains', unit_contains, 'position', position, 'title', title, 'name', name
      ) ORDER BY id ASC), '[]'::jsonb) INTO v_out FROM public.signers;
    WHEN 'units' THEN
      SELECT COALESCE(jsonb_agg(jsonb_build_object('id', id, 'name', name) ORDER BY id ASC), '[]'::jsonb)
      INTO v_out FROM public.units;
    WHEN 'uoms' THEN
      SELECT COALESCE(jsonb_agg(jsonb_build_object('id', id, 'name', name) ORDER BY id ASC), '[]'::jsonb)
      INTO v_out FROM public.uoms;
    ELSE
      PERFORM private.app_fail('Danh mục không hợp lệ: ' || COALESCE(p_table, ''));
  END CASE;
  RETURN v_out;
END;
$$;

CREATE OR REPLACE FUNCTION private.create_backup_snapshot(p_username text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_name text;
  v_payload jsonb;
  v_id bigint;
BEGIN
  v_payload := jsonb_build_object(
    'lines', COALESCE((SELECT jsonb_agg(private.line_base_to_jsonb(l) ORDER BY l.id) FROM public.lines l), '[]'::jsonb),
    'requests', COALESCE((SELECT jsonb_agg(private.request_to_jsonb(r) ORDER BY r.id) FROM public.requests r), '[]'::jsonb),
    'receipts', COALESCE((SELECT jsonb_agg(private.receipt_to_jsonb(rc) ORDER BY rc.id) FROM public.receipts rc), '[]'::jsonb),
    'suppliers', private.catalog_table_jsonb('suppliers'),
    'project_items', private.catalog_table_jsonb('project_items'),
    'material_groups', private.catalog_table_jsonb('material_groups'),
    'signers', private.catalog_table_jsonb('signers'),
    'units', private.catalog_table_jsonb('units'),
    'uoms', private.catalog_table_jsonb('uoms'),
    'users', COALESCE((SELECT jsonb_agg(private.profile_to_jsonb(p) ORDER BY p.created_at ASC NULLS FIRST, lower(p.username) ASC, p.id ASC) FROM public.profiles p), '[]'::jsonb),
    'sequences', COALESCE((SELECT jsonb_agg(jsonb_build_object('id', s.id, 'key', s.key, 'last_value', s.last_value) ORDER BY s.id) FROM public.sequences s), '[]'::jsonb)
  );

  v_name := 'NCVT_backup - backup ' || to_char(private.app_now() AT TIME ZONE 'Asia/Ho_Chi_Minh', 'YYYY-MM-DD HH24MI');

  INSERT INTO private.backup_snapshots (name, created_at, created_by, payload)
  VALUES (v_name, private.app_now(), p_username, v_payload)
  RETURNING id INTO v_id;

  v_name := v_name || ' #' || v_id;
  UPDATE private.backup_snapshots SET name = v_name WHERE id = v_id;

  DELETE FROM private.backup_snapshots
  WHERE id NOT IN (
    SELECT id FROM private.backup_snapshots
    ORDER BY created_at DESC, id DESC
    LIMIT 30
  );

  RETURN v_name;
END;
$$;

