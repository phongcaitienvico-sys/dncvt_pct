-- =============================================================================
-- 002_payments.sql
-- Tính năng "Đề nghị thanh toán" (ĐNTT): danh mục người đề nghị (payers),
-- giấy đề nghị thanh toán (payment_requests) và dòng thanh toán (payment_lines).
-- Chạy SAU 001_schema_rls_rpc.sql. Idempotent: chạy lại nhiều lần không lỗi,
-- không nhân đôi dữ liệu seed. KHÔNG đụng vào bảng vật tư (lines/requests/...).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. BẢNG
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.payers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NULL,
  position text NULL,
  unit text NULL
);

CREATE TABLE IF NOT EXISTS public.payment_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  year int NOT NULL,
  seq int NOT NULL,
  issued_at timestamptz NULL,
  issued_by text NULL,
  header_json jsonb DEFAULT '{}'::jsonb,
  line_count int NOT NULL DEFAULT 0 CHECK (line_count >= 0),
  total numeric NOT NULL DEFAULT 0,
  paid boolean NOT NULL DEFAULT false,
  paid_date date NULL,
  paid_by text NULL,
  legacy_flag boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX IF NOT EXISTS payment_requests_code_upper_idx ON public.payment_requests (upper(code));
CREATE UNIQUE INDEX IF NOT EXISTS payment_requests_year_seq_nonlegacy_idx ON public.payment_requests (year, seq) WHERE legacy_flag = false;
CREATE INDEX IF NOT EXISTS payment_requests_issued_at_idx ON public.payment_requests (issued_at DESC);

CREATE TABLE IF NOT EXISTS public.payment_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_code text NULL,
  pay_date date NULL,
  content text NULL,
  amount numeric NULL CHECK (amount >= 0),
  orderer text NULL,
  requester text NULL,
  supplier text NULL,
  driver_phone text NULL,
  plate_no text NULL,
  receive_time text NULL,
  receive_place text NULL,
  note text NULL,
  legacy_flag boolean NOT NULL DEFAULT false,
  created_by text NULL,
  created_at timestamptz DEFAULT private.app_now(),
  updated_at timestamptz DEFAULT private.app_now()
);
CREATE INDEX IF NOT EXISTS payment_lines_request_code_idx ON public.payment_lines (request_code);
CREATE INDEX IF NOT EXISTS payment_lines_pay_date_idx ON public.payment_lines (pay_date);

-- Đồng bộ identity khi import id tường minh (giống 001)
DO $$
DECLARE
  v_tbl text;
BEGIN
  FOREACH v_tbl IN ARRAY ARRAY['payers', 'payment_requests', 'payment_lines'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_sync_identity ON public.%I;', v_tbl);
    EXECUTE format(
      'CREATE TRIGGER trg_sync_identity AFTER INSERT ON public.%I FOR EACH STATEMENT EXECUTE FUNCTION private.sync_table_identity();',
      v_tbl
    );
  END LOOP;
END
$$;

