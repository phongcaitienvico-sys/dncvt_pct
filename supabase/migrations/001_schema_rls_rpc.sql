CREATE OR REPLACE FUNCTION private.clean_str(p_val jsonb, p_label text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v_type text;
  v_s text;
BEGIN
  IF p_val IS NULL THEN
    RETURN NULL;
  END IF;
  v_type := jsonb_typeof(p_val);
  IF v_type = 'null' THEN
    RETURN NULL;
  END IF;
  IF v_type IN ('object', 'array') THEN
    PERFORM private.app_fail('Giá trị không hợp lệ ở "' || p_label || '"');
  END IF;
  v_s := p_val #>> '{}';
  v_s := regexp_replace(v_s, '[\x00-\x08\x0B\x0C\x0E-\x1F]', '', 'g');
  v_s := regexp_replace(v_s, '^[\s\u00A0]+|[\s\u00A0]+$', '', 'g');
  IF char_length(v_s) > 1000 THEN
    PERFORM private.app_fail('"' || p_label || '" quá dài (tối đa 1000 ký tự)');
  END IF;
  IF v_s = '' THEN
    RETURN NULL;
  END IF;
  RETURN v_s;
END;
$$;

CREATE OR REPLACE FUNCTION private.clean_num(p_val jsonb, p_label text)
RETURNS numeric
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v_type text;
  v_s text;
  v_n numeric;
BEGIN
  IF p_val IS NULL THEN
    RETURN NULL;
  END IF;
  v_type := jsonb_typeof(p_val);
  IF v_type = 'null' THEN
    RETURN NULL;
  END IF;
  IF v_type = 'number' THEN
    v_n := (p_val #>> '{}')::numeric;
  ELSIF v_type = 'string' THEN
    v_s := regexp_replace(p_val #>> '{}', '^[\s\u00A0]+|[\s\u00A0]+$', '', 'g');
    IF v_s = '' THEN
      RETURN NULL;
    END IF;
    v_s := regexp_replace(v_s, ',', '.');
    IF v_s !~ '^[+-]?(\d+(\.\d*)?|\.\d+)([eE][+-]?\d+)?$' THEN
      PERFORM private.app_fail('"' || p_label || '" phải là số');
    END IF;
    BEGIN
      v_n := v_s::numeric;
    EXCEPTION WHEN OTHERS THEN
      PERFORM private.app_fail('"' || p_label || '" phải là số');
    END;
  ELSE
    PERFORM private.app_fail('"' || p_label || '" phải là số');
  END IF;

  IF v_n < 0 THEN
    PERFORM private.app_fail('"' || p_label || '" không được âm');
  END IF;
  RETURN trim_scale(v_n);
END;
$$;

CREATE OR REPLACE FUNCTION private.to_iso_date(p_raw text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v_s text;
  v_m text[];
BEGIN
  IF p_raw IS NULL THEN
    RETURN NULL;
  END IF;
  v_s := regexp_replace(p_raw, '^[\s\u00A0]+|[\s\u00A0]+$', '', 'g');
  IF v_s = '' THEN
    RETURN NULL;
  END IF;
  v_m := regexp_match(v_s, '^(\d{4})-(\d{1,2})-(\d{1,2})(?:[T\s].*)?$');
  IF v_m IS NOT NULL THEN
    RETURN v_m[1] || '-' || lpad(v_m[2], 2, '0') || '-' || lpad(v_m[3], 2, '0');
  END IF;
  v_m := regexp_match(v_s, '^(\d{1,2})[/\-.](\d{1,2})[/\-.](\d{4})$');
  IF v_m IS NOT NULL THEN
    RETURN v_m[3] || '-' || lpad(v_m[2], 2, '0') || '-' || lpad(v_m[1], 2, '0');
  END IF;
  RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION private.clean_date(p_val jsonb, p_label text)
RETURNS date
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v_type text;
  v_raw text;
  v_iso text;
  v_d date;
BEGIN
  IF p_val IS NULL THEN
    RETURN NULL;
  END IF;
  v_type := jsonb_typeof(p_val);
  IF v_type = 'null' THEN
    RETURN NULL;
  END IF;
  IF v_type <> 'string' THEN
    PERFORM private.app_fail('"' || p_label || '" không phải ngày hợp lệ');
  END IF;
  v_raw := regexp_replace(p_val #>> '{}', '^[\s\u00A0]+|[\s\u00A0]+$', '', 'g');
  IF v_raw = '' THEN
    RETURN NULL;
  END IF;
  v_iso := private.to_iso_date(v_raw);
  IF v_iso IS NULL THEN
    PERFORM private.app_fail('"' || p_label || '" không phải ngày hợp lệ');
  END IF;
  BEGIN
    v_d := v_iso::date;
  EXCEPTION WHEN OTHERS THEN
    PERFORM private.app_fail('"' || p_label || '" không phải ngày hợp lệ');
  END;
  IF to_char(v_d, 'YYYY-MM-DD') <> v_iso THEN
    PERFORM private.app_fail('"' || p_label || '" không phải ngày hợp lệ');
  END IF;
  RETURN v_d;
END;
$$;

CREATE OR REPLACE FUNCTION private.clean_ids(p_val jsonb)
RETURNS bigint[]
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v_elem jsonb;
  v_txt text;
  v_id bigint;
  v_out bigint[] := ARRAY[]::bigint[];
BEGIN
  IF p_val IS NULL OR jsonb_typeof(p_val) <> 'array' THEN
    PERFORM private.app_fail('Danh sách id không hợp lệ');
  END IF;
  FOR v_elem IN SELECT value FROM jsonb_array_elements(p_val) LOOP
    v_txt := COALESCE(v_elem #>> '{}', 'null');
    IF jsonb_typeof(v_elem) NOT IN ('number', 'string') OR v_txt !~ '^\s*[1-9]\d*\s*$' THEN
      PERFORM private.app_fail('Id không hợp lệ: ' || v_txt);
    END IF;
    v_id := btrim(v_txt)::bigint;
    IF NOT (v_id = ANY(v_out)) THEN
      v_out := array_append(v_out, v_id);
    END IF;
  END LOOP;
  RETURN v_out;
END;
$$;

