AS $$
DECLARE
  v_now_iso text;
  v_since_raw text;
  v_since_ts timestamptz;
  v_threshold_iso text := NULL;
  v_mode text;
  v_partial boolean;
  v_from_iso text;
  v_from_date date;
  v_ids jsonb;
  v_rows jsonb;
  v_recv jsonb;
  v_cols jsonb := jsonb_build_array(
    'id', 'request_code', 'unit', 'material_group', 'name', 'uom',
    'qty_requested', 'qty_on_hand', 'need_date', 'project_code', 'project_name',
    'purpose', 'equipment_name', 'delivery_location', 'requester', 'request_date',
    'supplier', 'unit_price', 'note', 'legacy_flag', 'created_by', 'created_at',
    'updated_at'
  );
BEGIN
  PERFORM private.require_user(false);
  v_now_iso := private.now_str();

  v_since_raw := NULLIF(COALESCE(p_params->>'since', ''), '');
  IF v_since_raw IS NOT NULL THEN
    BEGIN
      IF v_since_raw ~ '([+-]\d{2}:?\d{2}|Z)$' THEN
        v_since_ts := v_since_raw::timestamptz;
      ELSE
        v_since_ts := (v_since_raw || '+07:00')::timestamptz;
      END IF;
    EXCEPTION WHEN OTHERS THEN
      PERFORM private.app_fail('Mốc đồng bộ không hợp lệ');
    END;
    v_threshold_iso := private.fmt_ts(v_since_ts - interval '2 minutes');
  END IF;

  v_mode := COALESCE(p_params->>'mode', '');
  v_partial := v_mode IN ('recent', 'older');

  IF v_partial THEN
    v_from_iso := private.to_iso_date(p_params->>'from');
    IF v_from_iso IS NULL THEN
      PERFORM private.app_fail('Mốc ngày không hợp lệ');
    END IF;
    BEGIN
      v_from_date := v_from_iso::date;
    EXCEPTION WHEN OTHERS THEN
      PERFORM private.app_fail('Mốc ngày không hợp lệ');
    END;
    IF to_char(v_from_date, 'YYYY-MM-DD') <> v_from_iso THEN
      PERFORM private.app_fail('Mốc ngày không hợp lệ');
    END IF;

    SELECT
      COALESCE(jsonb_agg(l.id ORDER BY l.id ASC), '[]'::jsonb),
      COALESCE(jsonb_agg(private.line_row_23(l) ORDER BY l.id ASC), '[]'::jsonb)
    INTO v_ids, v_rows
    FROM public.lines l
    WHERE ((l.request_code IS NULL OR l.request_code = '' OR l.request_date IS NULL OR l.request_date >= v_from_date)
           = (v_mode = 'recent'));
  ELSIF v_threshold_iso IS NULL THEN
    SELECT
      COALESCE(jsonb_agg(l.id ORDER BY l.id ASC), '[]'::jsonb),
      COALESCE(jsonb_agg(private.line_row_23(l) ORDER BY l.id ASC), '[]'::jsonb)
    INTO v_ids, v_rows
    FROM public.lines l;
  ELSE
    SELECT COALESCE(jsonb_agg(l.id ORDER BY l.id ASC), '[]'::jsonb)
      INTO v_ids
    FROM public.lines l;

    SELECT COALESCE(jsonb_agg(private.line_row_23(l) ORDER BY l.id ASC), '[]'::jsonb)
      INTO v_rows
    FROM public.lines l
    WHERE private.fmt_ts(l.updated_at) >= v_threshold_iso;
  END IF;

  SELECT COALESCE(
    jsonb_object_agg(
      l.id::text,
      jsonb_build_array(private.num_json(round(l.qty_received, 3)), private.fmt_date(l.last_received_date))
    ),
    '{}'::jsonb
  )
  INTO v_recv
  FROM public.lines l
  WHERE l.qty_received <> 0 OR l.last_received_date IS NOT NULL;

  RETURN jsonb_build_object(
    'now', v_now_iso,
    'full', (v_threshold_iso IS NULL AND NOT v_partial),
    'partial', v_partial,
    'columns', v_cols,
    'rows', v_rows,
    'ids', v_ids,
    'recv', v_recv
  );
END;
$$;

-- 7.5 Lines Save (17 trường whitelist, LOCKED_FIELD, audit_log)
CREATE OR REPLACE FUNCTION public.rpc_lines_save(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_is_admin boolean;
  v_lines jsonb;
  v_len int;
  v_item jsonb;
  v_patch jsonb;
  v_id bigint;
  v_upd_ids bigint[] := ARRAY[]::bigint[];
  v_updates jsonb := '[]'::jsonb;
  v_inserts jsonb := '[]'::jsonb;
  v_before public.lines;
  v_after public.lines;
  v_before_json jsonb;
  v_merged jsonb;
  v_changed text[];
  v_f text;
  v_label text;
  v_now timestamptz;
  v_result jsonb := '[]'::jsonb;
  v_entry jsonb;
  v_field_order CONSTANT text[] := ARRAY[
    'unit', 'material_group', 'name', 'uom', 'qty_requested', 'qty_on_hand',
    'need_date', 'project_code', 'project_name', 'purpose', 'equipment_name',
    'delivery_location', 'requester', 'request_date', 'supplier', 'unit_price', 'note'
  ];
BEGIN
  v_me := private.require_user(false);
  v_is_admin := v_me.role = 'admin';
  v_now := private.app_now();

  v_lines := p_params->'lines';
  IF v_lines IS NULL OR jsonb_typeof(v_lines) <> 'array' OR jsonb_array_length(v_lines) = 0 THEN
    PERFORM private.app_fail('Không có dòng nào để lưu');
  END IF;
  v_len := jsonb_array_length(v_lines);
  IF v_len > 2000 THEN
    PERFORM private.app_fail('Mỗi lần lưu tối đa 2000 dòng');
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(v_lines) LOOP
    v_patch := private.clean_line_patch(v_item);
    IF v_item ? 'id' AND v_item->'id' IS NOT NULL AND jsonb_typeof(v_item->'id') <> 'null' AND (v_item->>'id') <> '' AND (v_item->>'id') <> '0' THEN
      v_id := (private.clean_ids(jsonb_build_array(v_item->'id')))[1];
      v_upd_ids := array_append(v_upd_ids, v_id);
      v_updates := v_updates || jsonb_build_array(jsonb_build_object(
        'id', v_id,
        'has_key', v_item ? 'key',
        'key', v_item->'key',
        'patch', v_patch
      ));
    ELSE
      v_inserts := v_inserts || jsonb_build_array(jsonb_build_object(
        'has_key', v_item ? 'key',
        'key', v_item->'key',
        'patch', v_patch
      ));
    END IF;
  END LOOP;

  IF cardinality(v_upd_ids) > 0 THEN
    PERFORM 1 FROM public.lines WHERE id = ANY(v_upd_ids) ORDER BY id FOR UPDATE;

    FOR v_item IN SELECT value FROM jsonb_array_elements(v_updates) LOOP
      v_id := (v_item->>'id')::bigint;
      v_patch := v_item->'patch';
      SELECT * INTO v_before FROM public.lines WHERE id = v_id;
      IF NOT FOUND THEN
        PERFORM private.app_fail('Dòng #' || v_id || ' không còn tồn tại (có thể đã bị xóa).', 'NOT_FOUND');
      END IF;

      v_before_json := private.line_base_to_jsonb(v_before);
      v_changed := ARRAY[]::text[];
      FOREACH v_f IN ARRAY v_field_order LOOP
        IF (v_patch ? v_f) AND ((v_patch->v_f) IS DISTINCT FROM (v_before_json->v_f)) THEN
          v_changed := array_append(v_changed, v_f);
        END IF;
      END LOOP;

      IF v_before.request_code IS NOT NULL AND v_before.request_code <> '' AND NOT v_is_admin THEN
        FOREACH v_f IN ARRAY v_changed LOOP
          IF v_f IN ('name', 'qty_requested') THEN
            v_label := CASE WHEN v_f = 'name' THEN 'Tên vật tư' ELSE 'SL yêu cầu' END;
            PERFORM private.app_fail(
              'Dòng #' || v_id || ' đã thuộc phiếu ' || v_before.request_code || ': chỉ Quản trị được sửa "' || v_label || '".',
              'LOCKED_FIELD'
            );
          END IF;
        END LOOP;
      END IF;

      IF cardinality(v_changed) = 0 THEN
        v_after := v_before;
      ELSE
        v_merged := v_before_json || v_patch;
        UPDATE public.lines
        SET unit = v_merged->>'unit',
            material_group = v_merged->>'material_group',
            name = v_merged->>'name',
            uom = v_merged->>'uom',
            qty_requested = (v_merged->>'qty_requested')::numeric,
            qty_on_hand = (v_merged->>'qty_on_hand')::numeric,
            need_date = (v_merged->>'need_date')::date,
            project_code = v_merged->>'project_code',
            project_name = v_merged->>'project_name',
            purpose = v_merged->>'purpose',
            equipment_name = v_merged->>'equipment_name',
            delivery_location = v_merged->>'delivery_location',
            requester = v_merged->>'requester',
            request_date = (v_merged->>'request_date')::date,
            supplier = v_merged->>'supplier',
            unit_price = (v_merged->>'unit_price')::numeric,
            note = v_merged->>'note',
            updated_at = v_now
        WHERE id = v_id
        RETURNING * INTO v_after;

        IF v_before.request_code IS NOT NULL AND v_before.request_code <> '' THEN
          FOREACH v_f IN ARRAY v_changed LOOP
            PERFORM private.write_audit(
              v_me.username,
              'lines',
              v_id::text,
              v_f,
              COALESCE(v_before_json->>v_f, ''),
              COALESCE(v_patch->>v_f, '')
            );
          END LOOP;
        END IF;
      END IF;

      v_entry := CASE
        WHEN (v_item->>'has_key')::boolean THEN jsonb_build_object('key', v_item->'key', 'line', private.line_to_jsonb(v_after))
        ELSE jsonb_build_object('line', private.line_to_jsonb(v_after))
      END;
      v_result := v_result || jsonb_build_array(v_entry);
    END LOOP;
  END IF;

  IF jsonb_array_length(v_inserts) > 0 THEN
    FOR v_item IN SELECT value FROM jsonb_array_elements(v_inserts) LOOP
      v_patch := v_item->'patch';
      INSERT INTO public.lines (
        request_code, unit, material_group, name, uom,
        qty_requested, qty_on_hand, need_date, project_code, project_name,
        purpose, equipment_name, delivery_location, requester, request_date,
        supplier, unit_price, note, legacy_flag, created_by, created_at, updated_at
      )
      VALUES (
        NULL,
        v_patch->>'unit',
        v_patch->>'material_group',
        v_patch->>'name',
        v_patch->>'uom',
        (v_patch->>'qty_requested')::numeric,
        (v_patch->>'qty_on_hand')::numeric,
        (v_patch->>'need_date')::date,
        v_patch->>'project_code',
        v_patch->>'project_name',
        v_patch->>'purpose',
        v_patch->>'equipment_name',
        v_patch->>'delivery_location',
        v_patch->>'requester',
        (v_patch->>'request_date')::date,
        v_patch->>'supplier',
        (v_patch->>'unit_price')::numeric,
        v_patch->>'note',
        false,
        v_me.username,
        v_now,
        v_now
      )
      RETURNING * INTO v_after;

      v_entry := CASE
        WHEN (v_item->>'has_key')::boolean THEN jsonb_build_object('key', v_item->'key', 'line', private.line_to_jsonb(v_after))
        ELSE jsonb_build_object('line', private.line_to_jsonb(v_after))
      END;
      v_result := v_result || jsonb_build_array(v_entry);
    END LOOP;
  END IF;

  RETURN v_result;
END;
$$;

-- 7.6 Requests Issue
CREATE OR REPLACE FUNCTION public.rpc_requests_issue(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_lines jsonb;
  v_confirmed boolean;
  v_year int;
  v_seq bigint;
  v_code text;
  v_now timestamptz;
  v_header jsonb;
  v_line_ids bigint[];
BEGIN
  v_me := private.require_user(false);
  v_lines := private.lock_issuable_lines(p_params->'line_ids');
  v_confirmed := COALESCE((p_params->>'confirm_mixed')::boolean, false);
  PERFORM private.check_mixed_jsonb(v_lines, v_confirmed);

  v_now := private.app_now();
  v_year := extract(year FROM (v_now AT TIME ZONE 'Asia/Ho_Chi_Minh'))::int;

  INSERT INTO public.sequences (key, last_value)
  VALUES ('YC' || v_year, CASE WHEN v_year = 2026 THEN 294 ELSE 0 END)
  ON CONFLICT (key) DO NOTHING;

  UPDATE public.sequences
  SET last_value = last_value + 1
  WHERE key = 'YC' || v_year
  RETURNING last_value INTO v_seq;

  WHILE EXISTS (
    SELECT 1 FROM public.requests r
    WHERE upper(r.code) = upper(private.format_request_code(v_year, v_seq))
  ) LOOP
    UPDATE public.sequences
    SET last_value = last_value + 1
    WHERE key = 'YC' || v_year
    RETURNING last_value INTO v_seq;
  END LOOP;

  v_code := private.format_request_code(v_year, v_seq);
  v_header := private.build_header_jsonb(v_lines, p_params->'header');

  SELECT array_agg((value->>'id')::bigint ORDER BY (value->>'id')::bigint)
    INTO v_line_ids
  FROM jsonb_array_elements(v_lines);

  INSERT INTO public.requests (code, year, seq, issued_at, issued_by, header_json, line_count, legacy_flag)
  VALUES (
    v_code,
    v_year,
    v_seq::int,
    v_now,
    COALESCE(NULLIF(v_me.full_name, ''), v_me.username),
    v_header,
    cardinality(v_line_ids),
    false
  );

  UPDATE public.lines
  SET request_code = v_code,
      updated_at = v_now
  WHERE id = ANY(v_line_ids);

  PERFORM private.write_audit(
    v_me.username,
    'requests',
    v_code,
    '(xuất phiếu)',
    '',
    array_to_string(v_line_ids::text[], ',')
  );

  RETURN jsonb_build_object(
    'code', v_code,
    'line_ids', to_jsonb(v_line_ids)
  );
END;
$$;

-- 7.7 Requests Append
CREATE OR REPLACE FUNCTION public.rpc_requests_append(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_lines jsonb;
  v_code_in text;
  v_req public.requests;
  v_current jsonb;
  v_cur_cnt int;
  v_new_cnt int;
  v_confirmed boolean;
  v_old_h jsonb;
  v_add_h jsonb;
  v_header jsonb;
  v_f text;
  v_merged_parts text[];
  v_min_need text := NULL;
  v_now timestamptz;
  v_line_ids bigint[];
BEGIN
  v_me := private.require_user(false);
  v_lines := private.lock_issuable_lines(p_params->'line_ids');

  v_code_in := upper(btrim(COALESCE(p_params->>'code', '')));
  IF v_code_in = '' THEN
    PERFORM private.app_fail('Chưa nhập số phiếu.');
  END IF;

  SELECT * INTO v_req
  FROM public.requests r
  WHERE upper(r.code) = v_code_in
  FOR UPDATE;
  IF NOT FOUND THEN
    PERFORM private.app_fail('Không tìm thấy phiếu ' || v_code_in || '.', 'NOT_FOUND');
  END IF;
  IF v_req.legacy_flag THEN
    PERFORM private.app_fail('Phiếu ' || v_req.code || ' là phiếu lịch sử (nhập từ Sheet cũ), không thêm dòng được.');
  END IF;

  SELECT COALESCE(jsonb_agg(private.line_base_to_jsonb(l) ORDER BY l.id ASC), '[]'::jsonb)
    INTO v_current
  FROM (
    SELECT * FROM public.lines WHERE request_code = v_req.code ORDER BY id ASC FOR UPDATE
  ) l;

  v_cur_cnt := jsonb_array_length(v_current);
  v_new_cnt := jsonb_array_length(v_lines);
  IF v_cur_cnt + v_new_cnt > 200 THEN
    PERFORM private.app_fail(
      'Phiếu ' || v_req.code || ' đã có ' || v_cur_cnt || ' dòng, thêm ' || v_new_cnt || ' dòng sẽ vượt quá 200 dòng/phiếu.'
    );
  END IF;

  v_confirmed := COALESCE((p_params->>'confirm_mixed')::boolean, false);
  PERFORM private.check_mixed_jsonb(v_current || v_lines, v_confirmed);

  v_old_h := COALESCE(v_req.header_json, '{}'::jsonb);
  v_add_h := private.build_header_jsonb(v_lines, NULL);
  v_header := v_old_h;

  FOREACH v_f IN ARRAY ARRAY['unit', 'project_code', 'project_name', 'delivery_location', 'requester'] LOOP
    v_merged_parts := string_to_array(COALESCE(v_old_h->>v_f, ''), '; ')
                      || string_to_array(COALESCE(v_add_h->>v_f, ''), '; ');
    v_header := v_header || jsonb_build_object(v_f, private.distinct_nonempty_join(v_merged_parts));
  END LOOP;

  SELECT MIN(d) INTO v_min_need
  FROM unnest(ARRAY[NULLIF(v_old_h->>'need_date', ''), NULLIF(v_add_h->>'need_date', '')]) AS d
  WHERE d IS NOT NULL;
  v_header := v_header || jsonb_build_object('need_date', v_min_need);

  v_now := private.app_now();
  SELECT array_agg((value->>'id')::bigint ORDER BY (value->>'id')::bigint)
    INTO v_line_ids
  FROM jsonb_array_elements(v_lines);

  UPDATE public.requests
  SET header_json = v_header,
      line_count = v_cur_cnt + v_new_cnt
  WHERE id = v_req.id;

  UPDATE public.lines
  SET request_code = v_req.code,
      updated_at = v_now
  WHERE id = ANY(v_line_ids);

  PERFORM private.write_audit(
    v_me.username,
    'requests',
    v_req.code,
    '(thêm dòng vào phiếu)',
    '',
    array_to_string(v_line_ids::text[], ',')
  );

  RETURN jsonb_build_object(
    'code', v_req.code,
    'line_ids', to_jsonb(v_line_ids)
  );
END;
$$;

-- 7.8 Lines Create (thêm nhiều dòng + tùy chọn cấp số / gộp phiếu nguyên tử)
CREATE OR REPLACE FUNCTION public.rpc_lines_create(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_items jsonb;
  v_common jsonb;
  v_len int;
  v_idx int := 0;
  v_it jsonb;
  v_k text;
  v_v jsonb;
  v_merged jsonb;
  v_clean jsonb;
  v_clean_list jsonb := '[]'::jsonb;
  v_append_code text;
  v_req public.requests;
  v_current jsonb;
  v_confirmed boolean;
  v_now timestamptz;
  v_row public.lines;
  v_new_ids bigint[] := ARRAY[]::bigint[];
  v_code text := NULL;
  v_res_lines jsonb;
BEGIN
  v_me := private.require_user(false);
  v_items := CASE
    WHEN p_params ? 'items' AND jsonb_typeof(p_params->'items') = 'array' THEN p_params->'items'
    ELSE '[]'::jsonb
  END;
  v_len := jsonb_array_length(v_items);
  IF v_len = 0 THEN
    PERFORM private.app_fail('Chưa có vật tư nào để thêm.');
  END IF;
  IF v_len > 200 THEN
    PERFORM private.app_fail('Mỗi lần thêm tối đa 200 dòng.');
  END IF;

  v_common := CASE
    WHEN p_params ? 'common' AND jsonb_typeof(p_params->'common') = 'object' THEN p_params->'common'
    ELSE '{}'::jsonb
  END;

  FOR v_it IN SELECT value FROM jsonb_array_elements(v_items) LOOP
    v_idx := v_idx + 1;
    v_merged := v_common;
    IF v_it IS NOT NULL AND jsonb_typeof(v_it) = 'object' THEN
      FOR v_k, v_v IN SELECT key, value FROM jsonb_each(v_it) LOOP
        IF v_v IS NOT NULL AND jsonb_typeof(v_v) <> 'null' AND (v_v #>> '{}') <> '' THEN
          v_merged := v_merged || jsonb_build_object(v_k, v_v);
        END IF;
      END LOOP;
    END IF;
    v_clean := private.clean_line_patch(v_merged);
    IF NULLIF(v_clean->>'name', '') IS NULL THEN
      PERFORM private.app_fail('Dòng ' || v_idx || ': thiếu tên vật tư.');
    END IF;
    IF (v_clean->>'qty_requested') IS NULL OR (v_clean->>'qty_requested')::numeric <= 0 THEN
      PERFORM private.app_fail('Dòng ' || v_idx || ' (' || (v_clean->>'name') || '): số lượng phải lớn hơn 0.');
    END IF;
    IF NULLIF(v_clean->>'request_date', '') IS NULL THEN
      v_clean := v_clean || jsonb_build_object('request_date', private.today_str());
    END IF;
    v_clean_list := v_clean_list || jsonb_build_array(v_clean);
  END LOOP;

  v_append_code := btrim(COALESCE(p_params->>'append_code', ''));
  v_confirmed := COALESCE((p_params->>'confirm_mixed')::boolean, false);
  IF v_append_code <> '' THEN
    SELECT * INTO v_req
    FROM public.requests r
    WHERE upper(r.code) = upper(v_append_code)
    FOR UPDATE;
    IF NOT FOUND THEN
      PERFORM private.app_fail('Không tìm thấy phiếu ' || upper(v_append_code) || '.', 'NOT_FOUND');
    END IF;
    IF v_req.legacy_flag THEN
      PERFORM private.app_fail('Phiếu ' || v_req.code || ' là phiếu lịch sử (nhập từ Sheet cũ), không thêm dòng được.');
    END IF;
    SELECT COALESCE(jsonb_agg(private.line_base_to_jsonb(l) ORDER BY l.id ASC), '[]'::jsonb)
      INTO v_current
    FROM (
      SELECT * FROM public.lines WHERE request_code = v_req.code ORDER BY id ASC FOR UPDATE
    ) l;
    IF jsonb_array_length(v_current) + v_len > 200 THEN
      PERFORM private.app_fail(
        'Phiếu ' || v_req.code || ' đã có ' || jsonb_array_length(v_current) || ' dòng, thêm ' || v_len || ' dòng sẽ vượt quá 200 dòng/phiếu.'
      );
    END IF;
    PERFORM private.check_mixed_jsonb(v_current || v_clean_list, v_confirmed);
  END IF;

  v_now := private.app_now();
  FOR v_clean IN SELECT value FROM jsonb_array_elements(v_clean_list) LOOP
    INSERT INTO public.lines (
      request_code, unit, material_group, name, uom,
      qty_requested, qty_on_hand, need_date, project_code, project_name,
      purpose, equipment_name, delivery_location, requester, request_date,
      supplier, unit_price, note, legacy_flag, created_by, created_at, updated_at
    )
    VALUES (
      NULL,
      v_clean->>'unit',
      v_clean->>'material_group',
      v_clean->>'name',
      v_clean->>'uom',
      (v_clean->>'qty_requested')::numeric,
      (v_clean->>'qty_on_hand')::numeric,
      (v_clean->>'need_date')::date,
      v_clean->>'project_code',
      v_clean->>'project_name',
      v_clean->>'purpose',
      v_clean->>'equipment_name',
      v_clean->>'delivery_location',
      v_clean->>'requester',
      (v_clean->>'request_date')::date,
      v_clean->>'supplier',
      (v_clean->>'unit_price')::numeric,
      v_clean->>'note',
      false,
      v_me.username,
      v_now,
      v_now
    )
    RETURNING * INTO v_row;
    v_new_ids := array_append(v_new_ids, v_row.id);
  END LOOP;

  IF v_append_code <> '' THEN
    v_code := (public.rpc_requests_append(jsonb_build_object(
      'code', v_append_code,
      'line_ids', to_jsonb(v_new_ids),
      'confirm_mixed', true
    )))->>'code';
  ELSIF COALESCE((p_params->>'issue')::boolean, false) THEN
    v_code := (public.rpc_requests_issue(jsonb_build_object(
      'line_ids', to_jsonb(v_new_ids),
      'confirm_mixed', true,
      'header', p_params->'header'
    )))->>'code';
  END IF;

  PERFORM private.write_audit(
    v_me.username,
    'lines',
    array_to_string(v_new_ids::text[], ','),
    '(thêm bằng form)',
    '',
    cardinality(v_new_ids) || ' dòng' || CASE WHEN v_code IS NOT NULL THEN ', phiếu ' || v_code ELSE '' END
  );

  SELECT COALESCE(jsonb_agg(private.line_to_jsonb(l) ORDER BY l.id ASC), '[]'::jsonb)
    INTO v_res_lines
  FROM public.lines l
  WHERE l.id = ANY(v_new_ids);

  RETURN jsonb_build_object(
    'code', v_code,
    'lines', v_res_lines
  );
END;
$$;

-- 7.9 Lines Delete
CREATE OR REPLACE FUNCTION public.rpc_lines_delete(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_is_admin boolean;
  v_ids bigint[];
  v_id bigint;
  v_line public.lines;
  v_found_ids bigint[] := ARRAY[]::bigint[];
  v_codes text[] := ARRAY[]::text[];
  v_code text;
  v_cnt int;
  v_receipts_removed int := 0;
BEGIN
  v_me := private.require_user(false);
  v_is_admin := v_me.role = 'admin';
  v_ids := private.clean_ids(p_params->'ids');

  PERFORM 1 FROM public.lines WHERE id = ANY(v_ids) ORDER BY id FOR UPDATE;

  FOREACH v_id IN ARRAY v_ids LOOP
    SELECT * INTO v_line FROM public.lines WHERE id = v_id;
    IF FOUND THEN
      IF v_line.request_code IS NOT NULL AND v_line.request_code <> '' AND NOT v_is_admin THEN
        PERFORM private.app_fail(
          'Dòng #' || v_id || ' đã thuộc phiếu ' || v_line.request_code || ': chỉ Quản trị được xóa dòng đã có số phiếu.',
          'HAS_REQUEST'
        );
      END IF;
      v_found_ids := array_append(v_found_ids, v_id);
      IF v_line.request_code IS NOT NULL AND v_line.request_code <> '' AND NOT (v_line.request_code = ANY(v_codes)) THEN
        v_codes := array_append(v_codes, v_line.request_code);
      END IF;
    END IF;
  END LOOP;

  IF cardinality(v_codes) > 0 THEN
    FOREACH v_code IN ARRAY v_codes LOOP
      SELECT count(*)::int INTO v_cnt
      FROM public.lines l
      WHERE l.id = ANY(v_found_ids) AND l.request_code = v_code;

      UPDATE public.requests
      SET line_count = GREATEST(0, COALESCE(line_count, 0) - v_cnt)
      WHERE code = v_code;
    END LOOP;
  END IF;

  IF cardinality(v_found_ids) > 0 THEN
    SELECT count(*)::int INTO v_receipts_removed
    FROM public.receipts r
    WHERE r.line_id = ANY(v_found_ids);

    FOREACH v_id IN ARRAY v_found_ids LOOP
      SELECT * INTO v_line FROM public.lines WHERE id = v_id;
      PERFORM private.write_audit(
        v_me.username,
        'lines',
        v_id::text,
        '(xóa dòng)',
        COALESCE(v_line.name, '') || CASE
          WHEN v_line.request_code IS NOT NULL AND v_line.request_code <> ''
          THEN ' — phiếu ' || v_line.request_code
          ELSE ''
        END,
        ''
      );
    END LOOP;

    DELETE FROM public.lines WHERE id = ANY(v_found_ids);
  END IF;

  RETURN jsonb_build_object(
    'deleted', cardinality(v_found_ids),
    'requests', to_jsonb(v_codes),
    'receipts_removed', v_receipts_removed
  );
END;
$$;

