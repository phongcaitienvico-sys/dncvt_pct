-- payments.create
CREATE OR REPLACE FUNCTION public.rpc_payments_create(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_rows jsonb;
  v_len int;
  v_item jsonb;
  v_clean jsonb;
  v_clean_list jsonb := '[]'::jsonb;
  v_now timestamptz;
  v_by text;
  v_row public.payment_lines;
  v_new_ids bigint[] := ARRAY[]::bigint[];
  v_out jsonb := '[]'::jsonb;
BEGIN
  v_me := private.require_user(false);
  v_rows := p_params->'rows';
  IF v_rows IS NULL OR jsonb_typeof(v_rows) <> 'array' OR jsonb_array_length(v_rows) = 0 THEN
    PERFORM private.app_fail('Không có dòng nào để thêm.');
  END IF;
  v_len := jsonb_array_length(v_rows);
  IF v_len > 500 THEN
    PERFORM private.app_fail('Mỗi lần thêm tối đa 500 dòng.');
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(v_rows) LOOP
    v_clean := private.clean_payment_patch(v_item);
    IF NULLIF(v_clean->>'pay_date', '') IS NULL THEN
      v_clean := v_clean || jsonb_build_object('pay_date', private.today_str());
    END IF;
    v_clean_list := v_clean_list || jsonb_build_array(v_clean);
  END LOOP;

  v_now := private.app_now();
  v_by := COALESCE(NULLIF(v_me.full_name, ''), v_me.username);

  FOR v_clean IN SELECT value FROM jsonb_array_elements(v_clean_list) LOOP
    INSERT INTO public.payment_lines (
      request_code, pay_date, content, amount, orderer, requester, supplier,
      driver_phone, plate_no, receive_time, receive_place, note,
      legacy_flag, created_by, created_at, updated_at
    )
    VALUES (
      NULL,
      (v_clean->>'pay_date')::date,
      v_clean->>'content',
      (v_clean->>'amount')::numeric,
      v_clean->>'orderer',
      v_clean->>'requester',
      v_clean->>'supplier',
      v_clean->>'driver_phone',
      v_clean->>'plate_no',
      v_clean->>'receive_time',
      v_clean->>'receive_place',
      v_clean->>'note',
      false,
      v_by,
      v_now,
      v_now
    )
    RETURNING * INTO v_row;
    v_new_ids := array_append(v_new_ids, v_row.id);
    v_out := v_out || jsonb_build_array(private.payment_line_to_jsonb(v_row));
  END LOOP;

  PERFORM private.write_audit(
    v_me.username,
    'payment_lines',
    array_to_string(v_new_ids::text[], ','),
    '(thêm dòng)',
    '',
    cardinality(v_new_ids) || ' dòng'
  );

  RETURN v_out;
END;
$$;

-- payments.save
CREATE OR REPLACE FUNCTION public.rpc_payments_save(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_is_admin boolean;
  v_id bigint;
  v_patch jsonb;
  v_before public.payment_lines;
  v_after public.payment_lines;
  v_before_json jsonb;
  v_merged jsonb;
  v_changed text[] := ARRAY[]::text[];
  v_f text;
  v_field_order CONSTANT text[] := ARRAY[
    'pay_date', 'content', 'amount', 'orderer', 'requester', 'supplier',
    'driver_phone', 'plate_no', 'receive_time', 'receive_place', 'note'
  ];
BEGIN
  v_me := private.require_user(false);
  v_is_admin := v_me.role = 'admin';

  IF p_params->'id' IS NULL OR jsonb_typeof(p_params->'id') = 'null' THEN
    PERFORM private.app_fail('Thiếu id dòng.');
  END IF;
  v_id := (private.clean_ids(jsonb_build_array(p_params->'id')))[1];
  IF p_params->'patch' IS NULL OR jsonb_typeof(p_params->'patch') <> 'object' THEN
    PERFORM private.app_fail('Dữ liệu sửa không hợp lệ');
  END IF;
  v_patch := private.clean_payment_patch(p_params->'patch');

  SELECT * INTO v_before FROM public.payment_lines WHERE id = v_id FOR UPDATE;
  IF NOT FOUND THEN
    PERFORM private.app_fail('Dòng #' || v_id || ' không còn tồn tại (có thể đã bị xóa).', 'NOT_FOUND');
  END IF;

  v_before_json := private.payment_line_cmp_jsonb(v_before);
  FOREACH v_f IN ARRAY v_field_order LOOP
    IF (v_patch ? v_f) AND ((v_patch->v_f) IS DISTINCT FROM (v_before_json->v_f)) THEN
      v_changed := array_append(v_changed, v_f);
    END IF;
  END LOOP;

  IF cardinality(v_changed) = 0 THEN
    RETURN private.payment_line_to_jsonb(v_before);
  END IF;

  IF v_before.request_code IS NOT NULL AND v_before.request_code <> '' AND NOT v_is_admin THEN
    PERFORM private.app_fail(
      'Dòng #' || v_id || ' đã thuộc giấy đề nghị ' || v_before.request_code || ': chỉ Quản trị được sửa.',
      'LOCKED_FIELD'
    );
  END IF;

  v_merged := v_before_json || v_patch;
  UPDATE public.payment_lines
  SET pay_date = (v_merged->>'pay_date')::date,
      content = v_merged->>'content',
      amount = (v_merged->>'amount')::numeric,
      orderer = v_merged->>'orderer',
      requester = v_merged->>'requester',
      supplier = v_merged->>'supplier',
      driver_phone = v_merged->>'driver_phone',
      plate_no = v_merged->>'plate_no',
      receive_time = v_merged->>'receive_time',
      receive_place = v_merged->>'receive_place',
      note = v_merged->>'note',
      updated_at = private.app_now()
  WHERE id = v_id
  RETURNING * INTO v_after;

  FOREACH v_f IN ARRAY v_changed LOOP
    PERFORM private.write_audit(
      v_me.username,
      'payment_lines',
      v_id::text,
      v_f,
      COALESCE(v_before_json->>v_f, ''),
      COALESCE(v_patch->>v_f, '')
    );
  END LOOP;

  IF v_after.request_code IS NOT NULL AND v_after.request_code <> '' AND 'amount' = ANY(v_changed) THEN
    PERFORM 1 FROM public.payment_requests WHERE code = v_after.request_code FOR UPDATE;
    PERFORM private.payreq_recalc(v_after.request_code);
  END IF;

  RETURN private.payment_line_to_jsonb(v_after);
END;
$$;

-- payments.delete
CREATE OR REPLACE FUNCTION public.rpc_payments_delete(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_ids bigint[];
  v_line public.payment_lines;
  v_found_ids bigint[] := ARRAY[]::bigint[];
BEGIN
  v_me := private.require_user(false);
  v_ids := private.clean_ids(p_params->'ids');

  FOR v_line IN SELECT * FROM public.payment_lines WHERE id = ANY(v_ids) ORDER BY id FOR UPDATE LOOP
    IF v_line.request_code IS NOT NULL AND v_line.request_code <> '' THEN
      PERFORM private.app_fail(
        'Dòng #' || v_line.id || ' đã thuộc giấy đề nghị ' || v_line.request_code || ': không xóa được (Quản trị gỡ khỏi giấy trước).',
        'HAS_REQUEST'
      );
    END IF;
    v_found_ids := array_append(v_found_ids, v_line.id);
    PERFORM private.write_audit(
      v_me.username,
      'payment_lines',
      v_line.id::text,
      '(xóa dòng)',
      COALESCE(v_line.content, '') || ' — ' || private.num_str(v_line.amount),
      ''
    );
  END LOOP;

  IF cardinality(v_found_ids) > 0 THEN
    DELETE FROM public.payment_lines WHERE id = ANY(v_found_ids);
  END IF;

  RETURN jsonb_build_object('deleted', cardinality(v_found_ids));
END;
$$;

