-- 7.15 Data Purge & Backup Run (Admin)
CREATE OR REPLACE FUNCTION public.rpc_data_purge(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_before date;
  v_before_str text;
  v_gone_line_ids bigint[];
  v_gone_codes text[];
  v_live_codes text[];
  v_gone_req_ids bigint[];
  v_total_lines int;
  v_total_requests int;
  v_del_lines int;
  v_left_lines int;
  v_del_receipts int;
  v_del_requests int;
  v_left_requests int;
  v_backup text := NULL;
BEGIN
  v_me := private.require_user(true);
  SET LOCAL statement_timeout = '30s';

  v_before := private.clean_date(p_params->'before', 'Mốc ngày');
  IF v_before IS NULL THEN
    PERFORM private.app_fail('Chưa chọn mốc ngày.');
  END IF;
  IF v_before > private.today_date() THEN
    PERFORM private.app_fail('Mốc ngày không được sau hôm nay.');
  END IF;
  v_before_str := private.fmt_date(v_before);

  SELECT count(*)::int INTO v_total_lines FROM public.lines;
  SELECT count(*)::int INTO v_total_requests FROM public.requests;

  SELECT
    COALESCE(array_agg(l.id), ARRAY[]::bigint[]),
    COALESCE(array_agg(DISTINCT l.request_code) FILTER (WHERE l.request_code IS NOT NULL AND l.request_code <> ''), ARRAY[]::text[])
  INTO v_gone_line_ids, v_gone_codes
  FROM public.lines l
  WHERE l.request_date IS NOT NULL
    AND l.request_date < v_before
    AND (
      l.request_code IS NULL OR l.request_code = ''
      OR NOT EXISTS (
        SELECT 1 FROM public.lines l2
        WHERE l2.request_code = l.request_code
          AND (l2.request_date IS NULL OR l2.request_date >= v_before)
      )
    );

  SELECT COALESCE(array_agg(DISTINCT l.request_code), ARRAY[]::text[])
    INTO v_live_codes
  FROM public.lines l
  WHERE NOT (l.id = ANY(v_gone_line_ids))
    AND l.request_code IS NOT NULL AND l.request_code <> '';

  SELECT count(*)::int INTO v_del_receipts
  FROM public.receipts r
  WHERE r.line_id = ANY(v_gone_line_ids);

  SELECT COALESCE(array_agg(r.id), ARRAY[]::bigint[])
    INTO v_gone_req_ids
  FROM public.requests r
  WHERE NOT (r.code = ANY(v_live_codes))
    AND (
      r.code = ANY(v_gone_codes)
      OR r.issued_at IS NULL
      OR (r.issued_at AT TIME ZONE 'Asia/Ho_Chi_Minh')::date < v_before
    );

  v_del_lines := cardinality(v_gone_line_ids);
  v_left_lines := v_total_lines - v_del_lines;
  v_del_requests := cardinality(v_gone_req_ids);
  v_left_requests := v_total_requests - v_del_requests;

  IF COALESCE((p_params->>'confirm')::boolean, false) IS NOT TRUE THEN
    RETURN jsonb_build_object(
      'preview', true,
      'before', v_before_str,
      'lines', v_del_lines,
      'lines_left', v_left_lines,
      'receipts', v_del_receipts,
      'requests', v_del_requests,
      'requests_left', v_left_requests
    );
  END IF;

  IF v_del_lines = 0 AND v_del_requests = 0 AND v_del_receipts = 0 THEN
    RETURN jsonb_build_object(
      'preview', false,
      'backup', NULL,
      'before', v_before_str,
      'lines', 0,
      'lines_left', v_left_lines,
      'receipts', 0,
      'requests', 0,
      'requests_left', v_left_requests
    );
  END IF;

  v_backup := private.create_backup_snapshot(v_me.username);

  IF v_del_lines > 0 THEN
    DELETE FROM public.lines WHERE id = ANY(v_gone_line_ids);
  END IF;
  IF v_del_requests > 0 THEN
    DELETE FROM public.requests WHERE id = ANY(v_gone_req_ids);
  END IF;

  PERFORM private.write_audit(
    v_me.username,
    'lines',
    '',
    '(dọn dữ liệu trước ' || v_before_str || ')',
    '',
    v_del_lines || ' dòng, ' || v_del_requests || ' phiếu, ' || v_del_receipts || ' lần nhận; sao lưu: ' || v_backup
  );

  RETURN jsonb_build_object(
    'preview', false,
    'backup', v_backup,
    'before', v_before_str,
    'lines', v_del_lines,
    'lines_left', v_left_lines,
    'receipts', v_del_receipts,
    'requests', v_del_requests,
    'requests_left', v_left_requests
  );
END;
$$;

