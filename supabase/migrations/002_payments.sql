CREATE OR REPLACE FUNCTION private.clean_payment_patch(p_input jsonb)
RETURNS jsonb
LANGUAGE plpgsql
IMMUTABLE
SET search_path = ''
AS $$
DECLARE
  v_out jsonb := '{}'::jsonb;
BEGIN
  IF p_input IS NULL OR jsonb_typeof(p_input) <> 'object' THEN
    PERFORM private.app_fail('Dữ liệu dòng không hợp lệ');
  END IF;

  IF p_input ? 'pay_date' THEN v_out := v_out || jsonb_build_object('pay_date', private.fmt_date(private.clean_date(p_input->'pay_date', 'Ngày'))); END IF;
  IF p_input ? 'content' THEN v_out := v_out || jsonb_build_object('content', private.clean_str(p_input->'content', 'Nội dung')); END IF;
  IF p_input ? 'amount' THEN v_out := v_out || jsonb_build_object('amount', private.num_json(private.clean_num(p_input->'amount', 'Số tiền'))); END IF;
  IF p_input ? 'orderer' THEN v_out := v_out || jsonb_build_object('orderer', private.clean_str(p_input->'orderer', 'Người đặt hàng')); END IF;
  IF p_input ? 'requester' THEN v_out := v_out || jsonb_build_object('requester', private.clean_str(p_input->'requester', 'Người đề nghị')); END IF;
  IF p_input ? 'supplier' THEN v_out := v_out || jsonb_build_object('supplier', private.clean_str(p_input->'supplier', 'NCC')); END IF;
  IF p_input ? 'driver_phone' THEN v_out := v_out || jsonb_build_object('driver_phone', private.clean_str(p_input->'driver_phone', 'SĐT nhà xe')); END IF;
  IF p_input ? 'plate_no' THEN v_out := v_out || jsonb_build_object('plate_no', private.clean_str(p_input->'plate_no', 'Biển số')); END IF;
  IF p_input ? 'receive_time' THEN v_out := v_out || jsonb_build_object('receive_time', private.clean_str(p_input->'receive_time', 'Thời gian nhận')); END IF;
  IF p_input ? 'receive_place' THEN v_out := v_out || jsonb_build_object('receive_place', private.clean_str(p_input->'receive_place', 'Địa điểm nhận')); END IF;
  IF p_input ? 'note' THEN v_out := v_out || jsonb_build_object('note', private.clean_str(p_input->'note', 'Ghi chú')); END IF;

  RETURN v_out;
END;
$$;

CREATE OR REPLACE FUNCTION private.format_payreq_code(p_year int, p_seq bigint)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = ''
AS $$
  SELECT 'DN' || p_year || '-' || CASE
    WHEN length(p_seq::text) < 3 THEN lpad(p_seq::text, 3, '0')
    ELSE p_seq::text
  END;
$$;

-- Khóa (FOR UPDATE) và kiểm tra các dòng sắp gán vào giấy đề nghị. Trả về id đã sắp xếp.
CREATE OR REPLACE FUNCTION private.lock_payable_lines(p_line_ids_json jsonb)
RETURNS bigint[]
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_ids bigint[];
  v_id bigint;
  v_found_ids bigint[];
  v_missing text[] := ARRAY[]::text[];
  v_rec public.payment_lines;
  v_coded_ids bigint[] := ARRAY[]::bigint[];
  v_coded_codes text[] := ARRAY[]::text[];
  v_invalid_ids bigint[] := ARRAY[]::bigint[];
BEGIN
  v_ids := private.clean_ids(p_line_ids_json);
  IF cardinality(v_ids) = 0 THEN
    PERFORM private.app_fail('Chưa chọn dòng nào.');
  END IF;
  IF cardinality(v_ids) > 200 THEN
    PERFORM private.app_fail('Một giấy đề nghị tối đa 200 dòng.');
  END IF;

  SELECT COALESCE(array_agg(l.id ORDER BY l.id), ARRAY[]::bigint[])
    INTO v_found_ids
  FROM (
    SELECT id FROM public.payment_lines WHERE id = ANY(v_ids) ORDER BY id FOR UPDATE
  ) l;

  FOREACH v_id IN ARRAY v_ids LOOP
    IF NOT (v_id = ANY(v_found_ids)) THEN
      v_missing := array_append(v_missing, v_id::text);
    END IF;
  END LOOP;
  IF cardinality(v_missing) > 0 THEN
    PERFORM private.app_fail(
      'Không tìm thấy dòng #' || array_to_string(v_missing, ', #') || ' (có thể đã bị xóa).',
      'NOT_FOUND'
    );
  END IF;

  FOR v_rec IN SELECT * FROM public.payment_lines WHERE id = ANY(v_ids) ORDER BY id ASC LOOP
    IF v_rec.request_code IS NOT NULL AND v_rec.request_code <> '' THEN
      v_coded_ids := array_append(v_coded_ids, v_rec.id);
      v_coded_codes := array_append(v_coded_codes, v_rec.request_code);
    END IF;
    IF v_rec.content IS NULL OR v_rec.content = '' OR v_rec.amount IS NULL THEN
      v_invalid_ids := array_append(v_invalid_ids, v_rec.id);
    END IF;
  END LOOP;

  IF cardinality(v_coded_ids) > 0 THEN
    PERFORM private.app_fail(
      'Có ' || cardinality(v_coded_ids) || ' dòng đã có số giấy đề nghị (' ||
      array_to_string(private.distinct_trimmed(v_coded_codes), ', ') ||
      '). Hãy bỏ chọn các dòng này hoặc dùng "In lại".',
      'ALREADY_ISSUED',
      jsonb_build_object('line_ids', to_jsonb(v_coded_ids))
    );
  END IF;

  IF cardinality(v_invalid_ids) > 0 THEN
    PERFORM private.app_fail(
      'Dòng #' || array_to_string(v_invalid_ids::text[], ', #') || ' thiếu nội dung hoặc số tiền.',
      'INVALID',
      jsonb_build_object('line_ids', to_jsonb(v_invalid_ids))
    );
  END IF;

  SELECT array_agg(x ORDER BY x) INTO v_ids FROM unnest(v_ids) AS x;
  RETURN v_ids;
END;
$$;

-- Tính lại số dòng + tổng tiền của 1 giấy đề nghị từ các dòng thực tế
CREATE OR REPLACE FUNCTION private.payreq_recalc(p_code text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF p_code IS NULL OR p_code = '' THEN
    RETURN;
  END IF;
  UPDATE public.payment_requests r
  SET line_count = s.cnt,
      total = s.total
  FROM (
    SELECT count(*)::int AS cnt, COALESCE(trim_scale(SUM(COALESCE(l.amount, 0))), 0) AS total
    FROM public.payment_lines l
    WHERE l.request_code = p_code
  ) s
  WHERE r.code = p_code;
END;
$$;

