CREATE OR REPLACE FUNCTION private.sync_table_identity()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_seq text;
  v_max bigint;
  v_last bigint;
BEGIN
  v_seq := pg_catalog.pg_get_serial_sequence(TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME, 'id');
  IF v_seq IS NULL THEN
    RETURN NULL;
  END IF;
  EXECUTE pg_catalog.format('SELECT max(id) FROM %I.%I', TG_TABLE_SCHEMA, TG_TABLE_NAME) INTO v_max;
  IF v_max IS NULL OR v_max <= 0 THEN
    RETURN NULL;
  END IF;
  SELECT pg_catalog.pg_sequence_last_value(v_seq::regclass) INTO v_last;
  IF v_last IS NULL OR v_last < v_max THEN
    PERFORM pg_catalog.setval(v_seq, v_max, true);
  END IF;
  RETURN NULL;
END;
$$;

DO $$
DECLARE
  v_tbl text;
BEGIN
  FOREACH v_tbl IN ARRAY ARRAY[
    'requests', 'lines', 'receipts', 'suppliers', 'project_items',
    'material_groups', 'signers', 'units', 'uoms', 'audit_log', 'sequences'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_sync_identity ON public.%I;', v_tbl);
    EXECUTE format(
      'CREATE TRIGGER trg_sync_identity AFTER INSERT ON public.%I FOR EACH STATEMENT EXECUTE FUNCTION private.sync_table_identity();',
      v_tbl
    );
  END LOOP;
END
$$;

CREATE OR REPLACE FUNCTION private.recalc_line_receipts(
  p_line_id bigint,
  p_touch_ts timestamptz,
  p_is_insert boolean DEFAULT false
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_qty numeric;
  v_last date;
BEGIN
  IF p_line_id IS NULL THEN
    RETURN;
  END IF;
  SELECT COALESCE(trim_scale(round(SUM(r.qty), 3)), 0), MAX(r.received_date)
    INTO v_qty, v_last
  FROM public.receipts r
  WHERE r.line_id = p_line_id;

  UPDATE public.lines l
  SET qty_received = COALESCE(v_qty, 0),
      last_received_date = v_last,
      updated_at = CASE
        WHEN p_is_insert THEN
          CASE
            WHEN p_touch_ts IS NULL THEN l.updated_at
            WHEN l.updated_at IS NULL THEN p_touch_ts
            ELSE GREATEST(l.updated_at, p_touch_ts)
          END
        ELSE COALESCE(p_touch_ts, private.app_now())
      END
  WHERE l.id = p_line_id;
END;
$$;

CREATE OR REPLACE FUNCTION private.trg_receipts_sync_line()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    PERFORM private.recalc_line_receipts(OLD.line_id, private.app_now(), false);
    RETURN OLD;
  ELSIF TG_OP = 'UPDATE' THEN
    IF OLD.line_id IS DISTINCT FROM NEW.line_id THEN
      PERFORM private.recalc_line_receipts(OLD.line_id, private.app_now(), false);
    END IF;
    PERFORM private.recalc_line_receipts(NEW.line_id, private.app_now(), false);
    RETURN NEW;
  ELSE
    PERFORM private.recalc_line_receipts(
      NEW.line_id,
      COALESCE(NEW.created_at, private.app_now()),
      true
    );
    RETURN NEW;
  END IF;
END;
$$;

DROP TRIGGER IF EXISTS trg_receipts_sync_line ON public.receipts;
CREATE TRIGGER trg_receipts_sync_line
AFTER INSERT OR UPDATE OR DELETE ON public.receipts
FOR EACH ROW
EXECUTE FUNCTION private.trg_receipts_sync_line();

