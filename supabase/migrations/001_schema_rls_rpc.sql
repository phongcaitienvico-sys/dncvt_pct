CREATE OR REPLACE FUNCTION private.current_profile()
RETURNS public.profiles
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid uuid;
  v_exp numeric;
  v_sid_txt text;
  v_sid uuid;
  v_prof public.profiles;
BEGIN
  v_uid := auth.uid();
  IF v_uid IS NULL THEN
    RETURN NULL;
  END IF;
  v_exp := NULLIF(auth.jwt() ->> 'exp', '')::numeric;
  IF v_exp IS NOT NULL AND v_exp < extract(epoch FROM private.app_now()) THEN
    RETURN NULL;
  END IF;
  v_sid_txt := NULLIF(auth.jwt() ->> 'session_id', '');
  IF v_sid_txt IS NOT NULL THEN
    BEGIN
      v_sid := v_sid_txt::uuid;
    EXCEPTION WHEN OTHERS THEN
      RETURN NULL;
    END;
    IF NOT EXISTS (
      SELECT 1
      FROM auth.sessions s
      WHERE s.id = v_sid
        AND s.user_id = v_uid
        AND (s.not_after IS NULL OR s.not_after > private.app_now())
    ) THEN
      RETURN NULL;
    END IF;
  END IF;
  SELECT * INTO v_prof
  FROM public.profiles p
  WHERE p.id = v_uid AND p.active = true;
  IF NOT FOUND THEN
    RETURN NULL;
  END IF;
  RETURN v_prof;
END;
$$;

