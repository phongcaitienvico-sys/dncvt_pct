CREATE OR REPLACE FUNCTION public.rpc_catalog_save(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_table text;
  v_row jsonb;
  v_cols text[];
  v_req_cols text[];
  v_uniq_col text := NULL;
  v_col text;
  v_patch jsonb := '{}'::jsonb;
  v_id bigint := NULL;
  v_before jsonb := NULL;
  v_after jsonb;
  v_has_req boolean := false;
  v_req_labels text[] := ARRAY[]::text[];
  v_lbl text;
  v_dup_exists boolean := false;
  v_set_parts text[] := ARRAY[]::text[];
  v_ins_cols text[] := ARRAY[]::text[];
  v_ins_vals text[] := ARRAY[]::text[];
  v_saved jsonb;
BEGIN
  v_me := private.require_user(true);
  v_table := COALESCE(p_params->>'table', '');

  CASE v_table
    WHEN 'suppliers' THEN
      v_cols := ARRAY['code', 'name', 'address', 'phone', 'email', 'tax_code', 'field'];
      v_req_cols := ARRAY['code', 'name'];
      v_uniq_col := 'code';
    WHEN 'project_items' THEN
      v_cols := ARRAY['project_code', 'project_name', 'item_code', 'item_name', 'owner', 'status'];
      v_req_cols := ARRAY['item_code', 'item_name', 'project_code', 'project_name'];
      v_uniq_col := 'item_code';
    WHEN 'material_groups' THEN
      v_cols := ARRAY['name', 'description'];
      v_req_cols := ARRAY['name'];
      v_uniq_col := 'name';
    WHEN 'signers' THEN
      v_cols := ARRAY['unit_contains', 'position', 'title', 'name'];
      v_req_cols := ARRAY['title'];
      v_uniq_col := NULL;
    WHEN 'units' THEN
      v_cols := ARRAY['name'];
      v_req_cols := ARRAY['name'];
      v_uniq_col := 'name';
    WHEN 'uoms' THEN
      v_cols := ARRAY['name'];
      v_req_cols := ARRAY['name'];
      v_uniq_col := 'name';
    WHEN 'payers' THEN
      v_cols := ARRAY['name', 'position', 'unit'];
      v_req_cols := ARRAY['name'];
      v_uniq_col := 'name';
    ELSE
      PERFORM private.app_fail('Danh mục không hợp lệ: ' || v_table);
  END CASE;

  v_row := p_params->'row';
  IF v_row IS NULL OR jsonb_typeof(v_row) <> 'object' THEN
    PERFORM private.app_fail('Dữ liệu không hợp lệ');
  END IF;

  PERFORM pg_advisory_xact_lock(hashtext('catalog:' || v_table));

  FOREACH v_col IN ARRAY v_cols LOOP
    IF v_row ? v_col THEN
      v_patch := v_patch || jsonb_build_object(v_col, private.clean_str(v_row->v_col, v_col));
    END IF;
  END LOOP;

  IF v_row ? 'id' AND v_row->'id' IS NOT NULL AND jsonb_typeof(v_row->'id') <> 'null' AND (v_row->>'id') <> '' AND (v_row->>'id') <> '0' THEN
    v_id := (private.clean_ids(jsonb_build_array(v_row->'id')))[1];
    EXECUTE format('SELECT to_jsonb(t) FROM public.%I t WHERE t.id = $1 FOR UPDATE', v_table)
      INTO v_before USING v_id;
    IF v_before IS NULL THEN
      PERFORM private.app_fail('Không tìm thấy bản ghi', 'NOT_FOUND');
    END IF;
    v_after := v_before || v_patch;
  ELSE
    v_after := v_patch;
  END IF;

  FOREACH v_col IN ARRAY v_req_cols LOOP
    IF NULLIF(v_after->>v_col, '') IS NOT NULL THEN
      v_has_req := true;
    END IF;
    v_lbl := CASE v_col
      WHEN 'name' THEN 'Tên'
      WHEN 'code' THEN 'Mã'
      WHEN 'title' THEN 'Chức danh'
      WHEN 'item_code' THEN 'Mã hạng mục'
      WHEN 'item_name' THEN 'Tên hạng mục'
      WHEN 'project_code' THEN 'Mã dự án'
      WHEN 'project_name' THEN 'Tên dự án'
      ELSE v_col
    END;
    v_req_labels := array_append(v_req_labels, '"' || v_lbl || '"');
  END LOOP;

  IF NOT v_has_req THEN
    PERFORM private.app_fail('Chưa nhập ' || array_to_string(v_req_labels, ' hoặc ') || ' — mục trống không được lưu.');
  END IF;

  IF v_uniq_col IS NOT NULL AND NULLIF(v_after->>v_uniq_col, '') IS NOT NULL THEN
    IF v_before IS NULL OR private.catalog_key(v_before->>v_uniq_col) <> private.catalog_key(v_after->>v_uniq_col) THEN
      EXECUTE format(
        'SELECT EXISTS (SELECT 1 FROM public.%I t WHERE ($1::bigint IS NULL OR t.id <> $1) AND private.catalog_key(t.%I) = private.catalog_key($2))',
        v_table, v_uniq_col
      ) INTO v_dup_exists USING v_id, (v_after->>v_uniq_col);

      IF v_dup_exists THEN
        PERFORM private.app_fail('"' || (v_after->>v_uniq_col) || '" đã có trong danh mục.', 'DUPLICATE');
      END IF;
    END IF;
  END IF;

  IF v_id IS NOT NULL THEN
    FOREACH v_col IN ARRAY v_cols LOOP
      IF v_patch ? v_col THEN
        v_set_parts := array_append(v_set_parts, format('%I = %L', v_col, v_patch->>v_col));
      END IF;
    END LOOP;

    IF cardinality(v_set_parts) > 0 THEN
      EXECUTE format(
        'UPDATE public.%I SET %s WHERE id = $1 RETURNING to_jsonb(%I.*)',
        v_table, array_to_string(v_set_parts, ', '), v_table
      ) INTO v_saved USING v_id;
    ELSE
      v_saved := v_before;
    END IF;

    FOREACH v_col IN ARRAY v_cols LOOP
      IF (v_patch ? v_col) AND ((v_before->v_col) IS DISTINCT FROM (v_patch->v_col)) THEN
        PERFORM private.write_audit(
          v_me.username,
          v_table,
          v_id::text,
          v_col,
          COALESCE(v_before->>v_col, ''),
          COALESCE(v_patch->>v_col, '')
        );
      END IF;
    END LOOP;

    RETURN v_saved;
  ELSE
    FOREACH v_col IN ARRAY v_cols LOOP
      v_ins_cols := array_append(v_ins_cols, format('%I', v_col));
      v_ins_vals := array_append(v_ins_vals, format('%L', v_patch->>v_col));
    END LOOP;

    EXECUTE format(
      'INSERT INTO public.%I (%s) VALUES (%s) RETURNING to_jsonb(%I.*)',
      v_table, array_to_string(v_ins_cols, ', '), array_to_string(v_ins_vals, ', '), v_table
    ) INTO v_saved;

    PERFORM private.write_audit(
      v_me.username,
      v_table,
      (v_saved->>'id'),
      '(thêm)',
      '',
      v_patch::text
    );

    RETURN v_saved;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.rpc_catalog_delete(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_me public.profiles;
  v_table text;
  v_ids bigint[];
  v_id bigint;
  v_row jsonb;
  v_deleted int := 0;
BEGIN
  v_me := private.require_user(true);
  v_table := COALESCE(p_params->>'table', '');
  IF v_table NOT IN ('suppliers', 'project_items', 'material_groups', 'units', 'uoms', 'signers', 'payers') THEN
    PERFORM private.app_fail('Danh mục không hợp lệ');
  END IF;
  v_ids := private.clean_ids(p_params->'ids');

  FOREACH v_id IN ARRAY v_ids LOOP
    EXECUTE format('SELECT to_jsonb(t) FROM public.%I t WHERE t.id = $1 FOR UPDATE', v_table)
      INTO v_row USING v_id;
    IF v_row IS NOT NULL THEN
      PERFORM private.write_audit(v_me.username, v_table, v_id::text, '(xóa)', v_row::text, '');
    END IF;
  END LOOP;

  EXECUTE format('DELETE FROM public.%I WHERE id = ANY($1)', v_table) USING v_ids;
  GET DIAGNOSTICS v_deleted = ROW_COUNT;

  RETURN jsonb_build_object('deleted', v_deleted);
END;
$$;

CREATE OR REPLACE FUNCTION public.rpc_export_all(p_params jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  PERFORM private.require_user(true);
  SET LOCAL statement_timeout = '30s';

  RETURN jsonb_build_object(
    'lines', COALESCE((SELECT jsonb_agg(private.line_base_to_jsonb(l) ORDER BY l.id ASC) FROM public.lines l), '[]'::jsonb),
    'requests', COALESCE((SELECT jsonb_agg(private.request_to_jsonb(r) ORDER BY r.id ASC) FROM public.requests r), '[]'::jsonb),
    'receipts', COALESCE((SELECT jsonb_agg(private.receipt_to_jsonb(rc) ORDER BY rc.id ASC) FROM public.receipts rc), '[]'::jsonb),
    'suppliers', private.catalog_table_jsonb('suppliers'),
    'project_items', private.catalog_table_jsonb('project_items'),
    'material_groups', private.catalog_table_jsonb('material_groups'),
    'signers', private.catalog_table_jsonb('signers'),
    'units', private.catalog_table_jsonb('units'),
    'uoms', private.catalog_table_jsonb('uoms'),
    'users', COALESCE((SELECT jsonb_agg(private.profile_to_jsonb(p) ORDER BY p.created_at ASC NULLS FIRST, lower(p.username) ASC, p.id ASC) FROM public.profiles p), '[]'::jsonb),
    'audit_log', COALESCE((
      SELECT jsonb_agg(private.audit_to_jsonb(sub) ORDER BY sub.id ASC)
      FROM (SELECT * FROM public.audit_log ORDER BY id DESC LIMIT 10000) sub
    ), '[]'::jsonb),
    'sequences', COALESCE((
      SELECT jsonb_agg(jsonb_build_object('id', s.id, 'key', s.key, 'last_value', s.last_value) ORDER BY s.id ASC)
      FROM public.sequences s
    ), '[]'::jsonb),
    'payers', private.catalog_table_jsonb('payers'),
    'payment_requests', COALESCE((SELECT jsonb_agg(private.payment_request_to_jsonb(pr) ORDER BY pr.id ASC) FROM public.payment_requests pr), '[]'::jsonb),
    'payment_lines', COALESCE((SELECT jsonb_agg(private.payment_line_to_jsonb(pl) ORDER BY pl.id ASC) FROM public.payment_lines pl), '[]'::jsonb)
  );
END;
$$;

